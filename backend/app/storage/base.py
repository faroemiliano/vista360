from pathlib import Path
from typing import Protocol


class Storage(Protocol):
    def size(self, key: str) -> int: ...
    def download(self, key: str, destination: Path, limit: int) -> None: ...
    def put(self, key: str, source: Path) -> None: ...
    def delete(self, key: str) -> None: ...
    def upload_url(self, key: str, expires: int) -> str | None: ...
    def read_url(self, key: str, expires: int) -> str | None: ...
    def copy_from(self, source: "Storage", source_key: str, target_key: str) -> None: ...
