import { expect, test } from '@playwright/test'
import { navigate } from './navigationHelpers'

test('trabajo manual guiado conecta ida y vuelta, publica y registra entrega sin login del cliente', async ({ page, browser }, testInfo) => {
  test.skip(process.env.TEST_API !== '1', 'Requiere PostgreSQL y API temporal')
  test.setTimeout(90_000)
  page.setDefaultTimeout(10_000)
  const stamp = `${testInfo.project.name}-${Date.now()}`
  const title = `Trabajo ${stamp}`
  const steps = page.getByRole('group', { name: 'Pasos del trabajo', exact: true })
  await page.goto('/studio')
  await page.getByRole('button', { name: 'Crear una cuenta', exact: true }).click()
  await page.getByLabel('Email', { exact: true }).fill(`operator-${stamp}@example.com`)
  await page.getByLabel('Contraseña', { exact: true }).fill('Test-password-123!')
  await page.getByRole('button', { name: 'Registrarme', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Trabajos', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Crear organización cliente', exact: true }).click()
  await page.getByLabel('Nombre de la organización', { exact: true }).fill(`Estudio ${stamp}`)
  await page.getByRole('combobox', { name: 'Tipo de organización', exact: true }).selectOption('photographer')
  await page.getByRole('button', { name: 'Crear organización', exact: true }).click()
  await expect(page.getByRole('heading', { name: `Estudio ${stamp}`, exact: true })).toBeVisible()
  await navigate(page, 'Trabajos')
  await expect(page.getByRole('navigation', { name: 'Navegación principal', includeHidden: true }).getByRole('button', { includeHidden: true })).toHaveCount(4)
  await page.getByRole('button', { name: 'Nuevo trabajo', exact: true }).click()
  await page.getByLabel('Nombre del trabajo', { exact: true }).fill(title)
  await page.getByLabel('Nombre del contacto', { exact: true }).fill('Inmobiliaria de prueba')
  await page.getByLabel('Email de contacto', { exact: true }).fill('client-jobs@example.com')
  await page.getByLabel('WhatsApp de contacto', { exact: true }).fill('+54 911 12345678')
  await page.getByLabel('Localidad del trabajo', { exact: true }).fill('Buenos Aires')
  await page.getByLabel('Superficie aproximada (m²)', { exact: true }).fill('85')
  await page.getByLabel('Cantidad de ambientes', { exact: true }).fill('2')
  await page.getByRole('button', { name: 'Guardar y abrir trabajo', exact: true }).click()
  await expect(page.getByRole('heading', { name: title, exact: true })).toBeVisible()
  await expect(steps.getByRole('button', { name: '2 Visita', exact: true })).toHaveAttribute('aria-current', 'step')
  await expect(page.getByLabel('Detalle de la entrega', { exact: true })).toHaveCount(0)
  await page.getByLabel('Fecha y hora de visita', { exact: true }).fill('2026-11-10T10:00')
  await page.getByRole('textbox', { name: 'Notas operativas', exact: true }).fill('Ingresar por la puerta lateral')
  await page.getByRole('button', { name: 'Guardar visita y notas', exact: true }).click()
  await expect(page.getByText('Visita y notas guardadas.', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Confirmar trabajo', exact: true }).click()
  await expect(page.locator('.badge').first()).toHaveText('CONFIRMADO')
  await page.screenshot({ path: testInfo.outputPath('visita-guiada.png'), fullPage: true })
  await page.getByText('Cambiar estado del trabajo', { exact: true }).click()
  await expect(page.getByRole('combobox', { name: 'Próximo estado', exact: true }).locator('option:not([disabled])')).toHaveCount(8)
  await page.getByText('Cambiar estado del trabajo', { exact: true }).click()
  await page.getByRole('button', { name: 'Continuar a fotos', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Publicar recorrido', exact: true })).toHaveCount(0)
  for (const name of ['Living', 'Cocina']) {
    await page.getByLabel('Nombre del ambiente', { exact: true }).fill(name)
    await page.getByRole('button', { name: 'Agregar ambiente', exact: true }).click()
    await page.getByLabel(`Panorámica JPEG para ${name}`, { exact: true }).setInputFiles(process.env.TEST_PANORAMA_FILE!)
    await page.getByRole('button', { name: 'Subir panorámica', exact: true }).click()
    await expect(page.locator('.scene-items > li').filter({ has: page.getByText(name, { exact: true }) }).getByText('Panorámica validada.', { exact: true })).toBeVisible()
  }
  await page.screenshot({ path: testInfo.outputPath('fotos-guiadas.png'), fullPage: true })
  await page.getByRole('button', { name: 'Continuar a conexiones', exact: true }).click()
  await page.getByRole('button', { name: 'Usar Cocina como inicial', exact: true }).click()
  const kitchen = page.locator('.scene-items > li').filter({ has: page.getByText('Cocina', { exact: true }) })
  await expect(kitchen.getByText('Ambiente inicial', { exact: true })).toBeVisible()
  await page.reload()
  await expect(kitchen.getByText('Ambiente inicial', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Conectar Living', exact: true }).click()
  const editor = page.getByRole('region', { name: 'Editor del recorrido', exact: true })
  await editor.getByRole('button', { name: 'Usar Living como inicial', exact: true }).click()
  await expect(editor.getByText('Ambiente inicial', { exact: true })).toBeVisible()
  await expect(editor.locator('.viewer-frame')).toHaveAttribute('data-status', 'ready')
  await editor.locator('.panorama canvas').evaluate((canvas) => canvas.setAttribute('data-persistente', 'true'))
  await editor.getByRole('button', { name: 'Nuevo punto en el centro', exact: true }).click()
  await editor.getByLabel('Etiqueta del punto', { exact: true }).fill('Ir a Cocina')
  await editor.getByRole('combobox', { name: 'Ambiente de destino', exact: true }).selectOption({ label: 'Cocina' })
  await editor.getByRole('button', { name: 'Guardar punto', exact: true }).click()
  await editor.getByRole('button', { name: 'Crear también la vuelta', exact: true }).click()
  await expect(editor.getByLabel('Etiqueta del punto', { exact: true })).toHaveValue('Volver a Living')
  await expect(editor.getByRole('button', { name: 'Usar Cocina como inicial', exact: true })).toBeDisabled()
  await expect(editor.getByRole('button', { name: 'Guardar punto', exact: true })).toBeDisabled()
  await expect(editor.locator('.viewer-frame')).toHaveAttribute('data-status', 'ready')
  await editor.getByRole('button', { name: 'Nuevo punto en el centro', exact: true }).click()
  await editor.getByRole('button', { name: 'Guardar punto', exact: true }).click()
  await expect(editor.locator('.saved-hotspots')).toContainText('Cocina → Living')
  await expect(editor.locator('canvas[data-persistente="true"]')).toHaveCount(1)
  await editor.getByRole('button', { name: 'Cerrar editor', exact: true }).click()
  await page.getByRole('button', { name: 'Conectar Living', exact: true }).click()
  await editor.getByRole('button', { name: 'Editar punto Ir a Cocina', exact: true }).click()
  await editor.getByLabel('Etiqueta del punto', { exact: true }).fill('Entrar a cocina')
  await editor.getByRole('button', { name: 'Guardar punto', exact: true }).click()
  // Reuses the existing return rather than creating a duplicate.
  await editor.getByRole('button', { name: 'Crear también la vuelta', exact: true }).click()
  await expect(editor.getByLabel('Etiqueta del punto', { exact: true })).toHaveValue('Volver a Living')
  await expect(editor.locator('.saved-hotspots > li')).toHaveCount(1)
  await editor.getByRole('button', { name: 'Cancelar punto', exact: true }).click()
  await editor.getByRole('navigation', { name: 'Ambientes del recorrido' }).getByRole('button', { name: 'Living', exact: true }).click()
  await editor.getByRole('button', { name: 'Editar punto Entrar a cocina', exact: true }).click()
  await editor.getByLabel('Etiqueta del punto', { exact: true }).fill('Sin guardar')
  await page.screenshot({ path: testInfo.outputPath('conexiones-guiadas.png'), fullPage: true })
  page.once('dialog', (dialog) => dialog.dismiss())
  await steps.getByRole('button', { name: '5 Revisar', exact: true }).click()
  await expect(editor.getByLabel('Etiqueta del punto', { exact: true })).toHaveValue('Sin guardar')
  page.once('dialog', (dialog) => dialog.accept())
  await steps.getByRole('button', { name: '5 Revisar', exact: true }).click()
  await page.getByRole('button', { name: 'Previsualizar recorrido', exact: true }).click()
  const preview = page.getByRole('region', { name: 'Previsualización privada', exact: true })
  await expect(preview.locator('.viewer-frame')).toHaveAttribute('data-status', 'ready')
  await expect(preview.locator('.saved-hotspots')).toContainText('Entrar a cocina')
  await preview.getByRole('navigation', { name: 'Ambientes del recorrido' }).getByRole('button', { name: 'Cocina', exact: true }).click()
  await expect(preview.locator('.saved-hotspots')).toContainText('Volver a Living')
  await page.getByRole('button', { name: 'Cerrar previsualización', exact: true }).click()
  page.once('dialog', (dialog) => dialog.accept())
  await page.getByRole('button', { name: 'Publicar recorrido', exact: true }).click()
  await expect(page.getByText('Versión 1 publicada.', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Continuar a entrega', exact: true }).click()
  await page.getByRole('button', { name: 'Marcar como listo para entregar', exact: true }).click()
  await expect(page.locator('.badge').first()).toHaveText('PUBLICADO')
  const publicLink = await page.getByLabel('Enlace de entrega', { exact: true }).inputValue()
  await page.getByLabel('Detalle de la entrega', { exact: true }).fill('Enlace compartido por WhatsApp')
  await page.getByRole('checkbox').check()
  await page.getByRole('button', { name: 'Registrar entrega y finalizar', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Entrega registrada', exact: true })).toBeVisible()
  await expect(page.locator('.badge').first()).toHaveText('FINALIZADO')
  await page.screenshot({ path: testInfo.outputPath('trabajo-entregado.png'), fullPage: true })
  await steps.getByRole('button', { name: '2 Visita', exact: true }).click()
  await expect(page.getByRole('textbox', { name: 'Notas operativas', exact: true })).toHaveValue('Ingresar por la puerta lateral')
  await expect(page.getByRole('textbox', { name: 'Notas operativas', exact: true })).toBeDisabled()
  await page.reload()
  await expect(page.getByRole('heading', { name: title, exact: true })).toBeVisible()
  await expect(steps.getByRole('button', { name: '2 Visita', exact: true })).toHaveAttribute('aria-current', 'step')
  await steps.getByRole('button', { name: '6 Entregar', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Entrega registrada', exact: true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  const anonymous = await browser.newContext({ viewport: page.viewportSize()! })
  try {
    const visitor = await anonymous.newPage()
    await visitor.goto(publicLink)
    await expect(visitor.getByRole('heading', { name: title, exact: true })).toBeVisible()
    await expect(visitor.locator('.viewer-frame')).toHaveAttribute('data-status', 'ready')
    const assertImmersiveViewer = async () => {
      const frame = (await visitor.locator('.viewer-frame').boundingBox())!
      const viewport = visitor.viewportSize()!
      expect(frame.width).toBeGreaterThan(viewport.width * 0.94)
      expect(frame.height).toBeGreaterThan(viewport.height * (viewport.height < 500 ? 0.55 : 0.7))
      expect(frame.y + frame.height).toBeLessThanOrEqual(viewport.height)
      expect(await visitor.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    }
    await assertImmersiveViewer()
    await visitor.setViewportSize({ width: 844, height: 390 })
    await assertImmersiveViewer()
    await expect.poll(async () => {
      const frame = (await visitor.locator('.viewer-frame').boundingBox())!
      const canvas = (await visitor.locator('.panorama canvas').boundingBox())!
      return Math.abs(frame.width - canvas.width) + Math.abs(frame.height - canvas.height)
    }).toBeLessThan(2)
  } finally { await anonymous.close() }
  // Clientes is the same organization/person identity, not a second contact registration.
  await navigate(page, 'Gestionar clientes')
  await expect(page.getByRole('rowheader', { name: `Estudio ${stamp}`, exact: true })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Inmobiliaria de prueba', exact: true })).toHaveCount(0)
  page.once('dialog', (dialog) => dialog.dismiss())
  await page.getByRole('button', { name: `Eliminar cliente Estudio ${stamp}`, exact: true }).click()
  await expect(page.getByRole('rowheader', { name: `Estudio ${stamp}`, exact: true })).toBeVisible()
  page.once('dialog', (dialog) => dialog.accept())
  await page.getByRole('button', { name: `Eliminar cliente Estudio ${stamp}`, exact: true }).click()
  await expect(page.getByRole('rowheader', { name: `Estudio ${stamp}`, exact: true })).toHaveCount(0)
  await navigate(page, 'Organizaciones')
  await expect(page.getByRole('button', { name: `Abrir organización Estudio ${stamp}`, exact: true })).toHaveCount(0)
  await navigate(page, 'Trabajos')
  await expect(page.getByRole('combobox', { name: 'Cliente del trabajo', exact: true }).locator('option:checked')).toHaveText(`Estudio ${stamp} — eliminada`)
  await expect(page.getByRole('button', { name: 'Nuevo trabajo', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: `Abrir trabajo ${title}`, exact: true }).click()
  await expect(page.getByText(`Organización eliminada: Estudio ${stamp}. Este trabajo, su historial y su recorrido se conservan con los mismos permisos.`, { exact: true })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Entrega registrada', exact: true })).toBeVisible()
  await page.getByText('Historial del trabajo', { exact: true }).click()
  await expect(page.getByText('Entrega registrada por el operador: Enlace compartido por WhatsApp', { exact: true })).toBeVisible()
  await steps.getByRole('button', { name: '3 Fotos', exact: true }).click()
  await expect(page.getByText('Panorámica validada.', { exact: true })).toHaveCount(2)
  await page.screenshot({ path: testInfo.outputPath('trabajo-conservado.png'), fullPage: true })
  await navigate(page, 'Trabajos')
  await page.getByRole('button', { name: 'Ver recorridos conservados', exact: true }).click()
  await expect(page.getByRole('button', { name: `Abrir ${title}`, exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Nuevo trabajo', exact: true })).toHaveCount(0)
  const afterDeletion = await browser.newContext()
  try {
    const visitor = await afterDeletion.newPage()
    await visitor.goto(publicLink)
    await expect(visitor.getByRole('heading', { name: title, exact: true })).toBeVisible()
    await expect(visitor.locator('.viewer-frame')).toHaveAttribute('data-status', 'ready')
  } finally { await afterDeletion.close() }
})
