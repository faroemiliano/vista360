import { expect, test } from '@playwright/test'

test('portugués cubre inicio, registro, cuenta y clientes sin perder datos al cambiar idioma', async ({ page }, testInfo) => {
  test.skip(process.env.TEST_API !== '1' || process.env.AUTH_REQUIRE_VERIFIED_EMAIL === 'true', 'Requiere API temporal')
  test.setTimeout(90_000)
  page.setDefaultTimeout(10_000)
  const email = `idioma-${testInfo.project.name}-${Date.now()}@example.com`
  await page.goto('/inicio')
  await expect(page.getByRole('link', { name: 'Ingresar al estudio', exact: true })).toBeVisible()
  await page.getByRole('combobox', { name: 'Idioma', exact: true }).selectOption('pt-BR')
  await expect(page.locator('html')).toHaveAttribute('lang', 'pt-BR')
  await expect(page.getByRole('link', { name: 'Entrar no estúdio', exact: true })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Um plano para seu estúdio.', exact: true })).toBeVisible()
  await page.getByRole('link', { name: 'Escolher Profissional', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Criar conta', exact: true })).toBeVisible()
  await page.getByLabel('E-mail', { exact: true }).fill(email)
  await page.getByLabel('Senha', { exact: true }).fill('Test-password-123!')
  await page.getByRole('button', { name: 'Cadastrar-me', exact: true }).click()
  const account = page.getByRole('dialog', { name: 'Minha conta', exact: true })
  await expect(account.getByText('Você escolheu Profissional', { exact: true })).toBeVisible()
  await expect(account.getByText('Restam 14 dias', { exact: true })).toBeVisible()
  await account.getByRole('link', { name: 'Dados da minha conta', exact: true }).click()
  await account.getByLabel('Nome e sobrenome', { exact: true }).fill('Cocina')
  // La preferencia se cambia desde otra pestaña: la ficha abierta conserva lo escrito.
  const sibling = await page.context().newPage()
  await sibling.goto('/inicio')
  await sibling.getByRole('combobox', { name: 'Idioma', exact: true }).selectOption('es')
  await expect(page.locator('html')).toHaveAttribute('lang', 'es')
  await expect(page.getByRole('dialog', { name: 'Mi cuenta', exact: true }).getByLabel('Nombre y apellido', { exact: true })).toHaveValue('Cocina')
  await sibling.getByRole('combobox', { name: 'Idioma', exact: true }).selectOption('pt-BR')
  await sibling.close()
  await expect(account.getByLabel('Nome e sobrenome', { exact: true })).toHaveValue('Cocina')
  await account.getByRole('button', { name: 'Salvar dados da minha conta', exact: true }).click()
  await expect(account.getByRole('status')).toContainText('Dados da conta salvos')
  await account.getByRole('button', { name: 'Fechar Minha conta', exact: true }).click()
  await expect(page.getByRole('link', { name: 'Minha conta', exact: true })).toContainText('Cocina')
  const menu = page.getByRole('button', { name: 'Abrir menu', exact: true })
  if (await menu.isVisible()) await menu.click()
  await page.getByRole('navigation', { name: 'Navegação principal', exact: true }).getByRole('link', { name: 'Organizações', exact: true }).click()
  const form = page.getByRole('form', { name: 'Criar organização', exact: true })
  await form.getByLabel('Nome da organização', { exact: true }).fill('Trabajos')
  await form.getByRole('button', { name: 'Criar organização', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Trabajos', exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Trabajos', exact: true })).toBeVisible()
  await expect(page.getByRole('combobox', { name: 'Idioma', exact: true })).toHaveValue('pt-BR')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: testInfo.outputPath('estudio-portugues.png') })
  await page.getByRole('button', { name: 'Sair', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Entrar', exact: true })).toBeVisible()
  await page.getByLabel('E-mail', { exact: true }).fill(email)
  await page.getByLabel('Senha', { exact: true }).fill('Wrong-password-123!')
  await page.getByRole('button', { name: 'Entrar', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('E-mail ou senha incorretos')
  await page.getByLabel('E-mail', { exact: true }).fill(process.env.TEST_ADMIN_EMAIL!)
  await page.getByLabel('Senha', { exact: true }).fill('Test-password-123!')
  await page.getByRole('button', { name: 'Entrar', exact: true }).click()
  await expect(page.getByRole('link', { name: 'Minha conta', exact: true })).toBeVisible()
  if (await menu.isVisible()) await menu.click()
  await page.getByRole('navigation', { name: 'Navegação principal', exact: true }).getByRole('link', { name: 'Usuários cadastrados', exact: true }).click()
  await page.getByLabel('Buscar conta', { exact: true }).fill(email)
  await page.getByRole('button', { name: 'Buscar', exact: true }).click()
  const row = page.getByRole('table', { name: 'Usuários cadastrados', exact: true }).getByRole('row').filter({ hasText: email })
  await expect(row).toContainText('Teste')
  await row.getByRole('button', { name: `Gerenciar plano de ${email}`, exact: true }).click()
  const manager = page.getByRole('dialog', { name: 'Gerenciar plano', exact: true })
  await manager.getByRole('combobox', { name: 'Plano', exact: true }).selectOption('professional')
  await expect(manager.getByLabel('Meses a habilitar', { exact: true })).toHaveValue('1')
  await manager.getByLabel('Observação administrativa', { exact: true }).fill('Ativação de teste em português')
  page.once('dialog', dialog => dialog.accept())
  await manager.getByRole('button', { name: 'Atribuir ou renovar plano', exact: true }).click()
  await expect(manager.getByRole('status')).toContainText('Plano atualizado')
  await expect(manager.getByText('Profissional · Mensal', { exact: true })).toBeVisible()
  await manager.getByRole('button', { name: 'Fechar gestão do plano', exact: true }).click()
  await expect(row).toContainText('Profissional')
})

test('portugués está disponible en formularios públicos, seguridad y visor sin traducir el recorrido del cliente', async ({ page }) => {
  test.setTimeout(60_000)
  await page.goto('/inicio')
  await page.getByRole('combobox', { name: 'Idioma', exact: true }).selectOption('pt-BR')
  await expect(page.locator('html')).toHaveAttribute('lang', 'pt-BR')
  await page.route('**/api/v1/public/studios/idiomas', route => route.fulfill({ json: { name: 'Trabajos' } }))
  await page.goto('/solicitar/idiomas')
  await expect(page.getByRole('heading', { name: 'Trabajos', exact: true })).toBeVisible()
  await expect(page.getByRole('form', { name: 'Solicitar digitalização', exact: true })).toBeVisible()
  await expect(page.getByLabel('Nome', { exact: true })).toBeVisible()
  await expect(page).toHaveTitle('Solicitar fotografia · Trabajos')
  await page.getByRole('combobox', { name: 'Idioma', exact: true }).selectOption('es')
  await expect(page).toHaveTitle('Solicitar fotografía · Trabajos')
  await page.getByRole('combobox', { name: 'Idioma', exact: true }).selectOption('pt-BR')
  await expect(page).toHaveTitle('Solicitar fotografia · Trabajos')
  await page.goto('/cuenta/restablecer')
  await expect(page.getByRole('heading', { name: 'Escolha sua nova senha', exact: true })).toBeVisible()
  await page.route('**/api/v1/public/tours/idiomas', route => route.fulfill({ json: {
    schema_version: 1, version: 1, title: 'Mis recorridos', description: 'El texto del cliente no se traduce', start_scene_id: 'living',
    scenes: [{ id: 'living', name: 'Cocina', initial_view: { yaw: 0, pitch: 0, hfov: 110 },
      sources: [{ url: 'http://127.0.0.1:5175/panoramas/atrio-2048.png', width: 2048, height: 1024 }], hotspots: [] }],
  } }))
  await page.goto('/tour/idiomas')
  await expect(page.locator('.viewer-frame')).toHaveAttribute('data-status', 'ready', { timeout: 15_000 })
  await expect(page.getByRole('heading', { name: 'Mis recorridos', exact: true })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Cocina', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Aproximar', exact: true })).toBeVisible()
  await page.locator('.panorama canvas').evaluate(element => element.setAttribute('data-idioma', 'persistente'))
  await page.getByRole('combobox', { name: 'Idioma', exact: true }).selectOption('es')
  await expect(page.getByRole('button', { name: 'Acercar', exact: true })).toBeVisible()
  await expect(page.locator('canvas[data-idioma="persistente"]')).toHaveCount(1)
  await expect(page.getByRole('heading', { name: 'Mis recorridos', exact: true })).toBeVisible()
})
