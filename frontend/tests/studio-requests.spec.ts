import { expect, test, devices, type Page } from '@playwright/test'
import { navigate } from './navigationHelpers'

async function register(page: Page, email: string, name: string) {
  await page.goto('/studio')
  await page.getByRole('button', { name: 'Crear una cuenta', exact: true }).click()
  await page.getByLabel('Email', { exact: true }).fill(email)
  await page.getByLabel('Contraseña', { exact: true }).fill('Test-password-123!')
  await page.getByRole('button', { name: 'Registrarme', exact: true }).click()
  await page.getByRole('button', { name: 'Editar estudio', exact: true }).click()
  await page.getByLabel('Nombre del estudio', { exact: true }).fill(name)
  await page.getByRole('button', { name: 'Guardar estudio', exact: true }).click()
  await expect(page.getByRole('heading', { name, exact: true })).toBeVisible()
}

test('cada fotógrafo comparte su formulario y conserva sus consultas privadas', async ({ page, browser, baseURL }, testInfo) => {
  test.skip(process.env.TEST_API !== '1', 'Requiere API y PostgreSQL temporal')
  test.setTimeout(90_000)
  page.setDefaultTimeout(10_000)
  const stamp = `${testInfo.project.name}-${Date.now()}`
  const studioA = `Estudio Luz ${stamp}`, studioB = `Estudio Sur ${stamp}`
  const lead = `Cliente consulta ${stamp}`
  const device = testInfo.project.name.includes('mobile') ? devices['Pixel 7'] : {}
  const otherContext = await browser.newContext({ ...device, baseURL })
  const visitorContext = await browser.newContext({ ...device, baseURL })
  try {
    await register(page, `luz-${stamp}@example.com`, studioA)
    await navigate(page, 'Organizaciones')
    await page.getByLabel('Nombre de la organización', { exact: true }).fill('Inmobiliaria del cliente')
    await page.getByRole('combobox', { name: 'Tipo de organización', exact: true }).selectOption('agency')
    await page.getByRole('button', { name: 'Crear organización', exact: true }).click()
    await expect(page.getByRole('heading', { name: 'Inmobiliaria del cliente', exact: true })).toBeVisible()
    await navigate(page, 'Solicitudes web')
    await expect(page.getByRole('combobox', { name: 'Cliente del trabajo', exact: true })).toHaveCount(0)
    await page.getByRole('button', { name: 'Activar mi formulario', exact: true }).click()
    const linkA = await page.getByRole('textbox', { name: 'Mi enlace de solicitudes', exact: true }).inputValue()
    expect(linkA).toContain('/solicitar/')
    await page.reload()
    await expect(page.getByRole('textbox', { name: 'Mi enlace de solicitudes', exact: true })).toHaveValue(linkA)
    await page.screenshot({ path: testInfo.outputPath('mi-enlace.png'), fullPage: true })
    const other = await otherContext.newPage()
    await register(other, `sur-${stamp}@example.com`, studioB)
    await navigate(other, 'Solicitudes web')
    await expect(other.getByRole('combobox', { name: 'Cliente del trabajo', exact: true })).toHaveCount(0)
    await expect(other.getByRole('heading', { name: 'Registrá tu primer cliente', exact: true })).toHaveCount(0)
    await other.getByRole('button', { name: 'Activar mi formulario', exact: true }).click()
    expect(await other.getByRole('textbox', { name: 'Mi enlace de solicitudes', exact: true }).inputValue()).not.toBe(linkA)
    const visitor = await visitorContext.newPage()
    await visitor.goto(linkA)
    await expect(visitor.getByRole('heading', { name: studioA, exact: true })).toBeVisible()
    await expect(visitor.getByText('No necesitás una cuenta ni realizar un pago.', { exact: false })).toBeVisible()
    const form = visitor.getByRole('form', { name: 'Solicitar digitalización', exact: true })
    await form.getByLabel('Nombre', { exact: true }).fill(lead)
    await form.getByLabel('Email', { exact: true }).fill('client@example.com')
    await form.getByLabel('WhatsApp', { exact: true }).fill('+54 9 11 1234 5678')
    await form.getByRole('combobox', { name: 'Tipo de propiedad', exact: true }).selectOption('casa')
    await form.getByLabel('Localidad', { exact: true }).fill('Palermo')
    await form.getByLabel('Superficie aproximada (m²)', { exact: true }).fill('90')
    await form.getByLabel('Cantidad de ambientes', { exact: true }).fill('3')
    await form.getByLabel('Mensaje adicional', { exact: true }).fill('Fotografiar la propiedad la próxima semana')
    await form.getByRole('checkbox').check()
    await visitor.screenshot({ path: testInfo.outputPath('formulario-del-estudio.png'), fullPage: true })
    await form.getByRole('button', { name: 'Enviar solicitud de digitalización', exact: true }).click()
    await expect(visitor.getByRole('heading', { name: 'Ya registramos tu consulta.', exact: true })).toBeVisible()
    const receipt = await visitor.locator('[role="status"]').filter({ hasText: 'Tu referencia' }).textContent()
    const requestId = receipt!.match(/[a-f\d]{8}-(?:[a-f\d]{4}-){3}[a-f\d]{12}/i)![0]
    await page.getByRole('button', { name: 'Actualizar bandeja', exact: true }).click()
    await expect(page.getByRole('heading', { name: lead, exact: true })).toBeVisible()
    await page.screenshot({ path: testInfo.outputPath('consulta-privada.png'), fullPage: true })
    await other.getByRole('button', { name: 'Actualizar bandeja', exact: true }).click()
    await expect(other.getByRole('heading', { name: lead, exact: true })).toHaveCount(0)
    const foreignLink = new URL(other.url())
    foreignLink.searchParams.set('solicitud', requestId)
    await other.goto(foreignLink.href)
    await expect(other.getByRole('alert')).toContainText('Solicitud no encontrada')
    await expect(other.getByRole('heading', { name: lead, exact: true })).toHaveCount(0)
    const item = page.getByRole('article').filter({ has: page.getByRole('heading', { name: lead, exact: true }) })
    await item.getByRole('button', { name: `Preparar trabajo para ${lead}`, exact: true }).click()
    const customer = page.getByRole('combobox', { name: 'Cliente del trabajo', exact: true })
    await expect(customer).toHaveValue('')
    await page.getByRole('button', { name: 'Volver a solicitudes', exact: true }).click()
    await expect(customer).toHaveCount(0)
    await item.getByRole('button', { name: `Preparar trabajo para ${lead}`, exact: true }).click()
    await customer.selectOption({ label: 'Inmobiliaria del cliente' })
    await page.getByLabel('Nombre del trabajo', { exact: true }).fill(`Recorrido ${stamp}`)
    await page.getByRole('button', { name: 'Guardar y abrir trabajo', exact: true }).click()
    await expect(page).toHaveURL(/\/studio\/trabajos\/[a-f\d-]+/)
    await expect(page.getByRole('heading', { name: `Recorrido ${stamp}`, exact: true })).toBeVisible()
    await navigate(page, 'Solicitudes web')
    page.once('dialog', dialog => dialog.accept())
    await page.getByRole('button', { name: 'Desactivar enlace', exact: true }).click()
    await expect(page.getByRole('button', { name: 'Activar mi formulario', exact: true })).toBeVisible()
    await expect(page.getByRole('heading', { name: lead, exact: true })).toBeVisible()
    await visitor.goto(linkA)
    await expect(visitor.getByRole('alert')).toContainText('formulario no está disponible')
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  } finally { await otherContext.close(); await visitorContext.close() }
})
