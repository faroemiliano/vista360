import { expect, test } from '@playwright/test'
import { readFile } from 'node:fs/promises'

test('consumo visible y detalle por proyecto con archivos procesados', async ({ page, baseURL }, testInfo) => {
  test.skip(process.env.TEST_API !== '1' || process.env.AUTH_REQUIRE_VERIFIED_EMAIL === 'true', 'Requiere API temporal')
  test.setTimeout(60_000)
  const email = `consumo-${testInfo.project.name}-${Date.now()}@example.com`
  const api = 'http://127.0.0.1:8002'
  await page.goto('/studio')
  await page.getByRole('button', { name: 'Crear una cuenta', exact: true }).click()
  await page.getByLabel('Email', { exact: true }).fill(email)
  await page.getByLabel('Contraseña', { exact: true }).fill('Test-password-123!')
  await page.getByRole('button', { name: 'Registrarme', exact: true }).click()
  const meter = page.getByRole('region', { name: 'Almacenamiento de tu plan', exact: true })
  await expect(meter).toContainText('0 B')
  await expect(meter.getByRole('progressbar')).toHaveAttribute('value', '0')
  const session = await (await page.request.get(api + '/api/v1/auth/session')).json()
  const headers = { Origin: baseURL!, 'X-CSRF-Token': session.csrf_token }
  const tourResponse = await page.request.post(api + '/api/v1/tours', { headers, data: { title: 'Proyecto de consumo', slug: email.split('@')[0] } })
  expect(tourResponse.status()).toBe(201)
  const tour = await tourResponse.json()
  const sceneResponse = await page.request.post(`${api}/api/v1/tours/${tour.id}/scenes`, { headers, data: { name: 'Ambiente de prueba' } })
  expect(sceneResponse.status()).toBe(201)
  const scene = await sceneResponse.json()
  const photo = await readFile(process.env.TEST_PANORAMA_FILE!)
  const targetResponse = await page.request.post(`${api}/api/v1/tours/${tour.id}/scenes/${scene.id}/uploads`, { headers, data: { size_bytes: photo.length, mime_type: 'image/jpeg' } })
  expect(targetResponse.status()).toBe(201)
  const target = await targetResponse.json()
  expect((await page.request.put(api + target.url, { headers: { ...headers, 'Content-Type': 'image/jpeg' }, data: photo })).status()).toBe(204)
  expect((await page.request.post(`${api}/api/v1/assets/${target.asset_id}/complete`, { headers })).status()).toBe(200)
  await expect.poll(async () => (await (await page.request.get(`${api}/api/v1/assets/${target.asset_id}`)).json()).status).toBe('ready')
  await page.evaluate(() => window.dispatchEvent(new Event('focus')))
  await expect(meter.getByRole('progressbar')).not.toHaveAttribute('value', '0')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: testInfo.outputPath('consumo-panel.png') })
  await meter.getByRole('link', { name: 'Ver consumo', exact: true }).click()
  const account = page.getByRole('dialog', { name: 'Mi cuenta', exact: true })
  const details = account.getByRole('region', { name: 'Consumo por proyecto', exact: true })
  await expect(details.getByText('Proyecto de consumo', { exact: true })).toBeVisible()
  await expect(details.getByText('Originales', { exact: true })).toBeVisible()
  await expect(details.getByText('Copias publicadas', { exact: true })).toBeVisible()
  await expect(account.getByText('Reserva estimada de almacenamiento', { exact: false })).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('consumo-detalle.png') })
  await account.getByRole('button', { name: 'Cerrar Mi cuenta', exact: true }).click()
  await page.route('**/workspaces/*/subscription', route => route.fulfill({ status: 503, json: { detail: 'No disponible' } }))
  await expect.poll(async () => {
    await page.evaluate(() => window.dispatchEvent(new Event('focus')))
    return meter.innerText()
  }).toContain('No se pudo actualizar el consumo.')
  await page.unroute('**/workspaces/*/subscription')
  await meter.getByRole('button', { name: 'Reintentar', exact: true }).click()
  await expect(meter).not.toContainText('No se pudo actualizar el consumo.')
})
