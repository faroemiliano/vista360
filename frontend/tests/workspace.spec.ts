test('registro, recorrido, ambientes, orden, recarga y logout con API real', async ({ page }, testInfo) => {
  test.skip(process.env.TEST_API !== '1', 'Necesita la API y base temporal del runner backend')
  const email = `browser-${testInfo.project.name}-${Date.now()}@example.com`
  const title = `Casa prueba ${Date.now()}`
  const apiRequests: string[] = []
  page.on('request', (request) => {
    if (request.url().includes('/api/v1/')) apiRequests.push(request.url())
  })
  await page.goto('/')
  await page.getByRole('button', { name: 'Crear una cuenta', exact: true }).click()
  await page.getByLabel('Email', { exact: true }).fill(email)
  await page.getByLabel('Contraseña', { exact: true }).fill('Test-password-123!')
  await page.getByRole('button', { name: 'Registrarme', exact: true }).click()
  await navigate(page, 'Mis recorridos')
  await expect(page.getByRole('heading', { name: 'Mis recorridos', exact: true })).toBeVisible()
  expect(apiRequests.length).toBeGreaterThan(0)
  expect(apiRequests.every((url) => new URL(url).hostname === new URL(page.url()).hostname)).toBe(true)
  await page.getByLabel('Título', { exact: true }).fill(title)
  await page.getByRole('button', { name: 'Crear recorrido', exact: true }).click()
  await page.getByRole('button', { name: `Abrir ${title}`, exact: true }).click()
  for (const name of ['Living', 'Cocina']) {
    await page.getByLabel('Nombre del ambiente', { exact: true }).fill(name)
    await page.getByRole('button', { name: 'Agregar ambiente', exact: true }).click()
    await expect(page.locator('.scene-items')).toContainText(name)
    await expect(page.getByLabel('Nombre del ambiente', { exact: true })).toHaveValue('')
  }
  await page.getByLabel('Panorámica JPEG para Living', { exact: true }).setInputFiles(process.env.TEST_PANORAMA_FILE!)
  const living = page.locator('.scene-items li').filter({ has: page.getByRole('button', { name: 'Editar Living', exact: true }) })
  await living.getByRole('button', { name: 'Subir panorámica', exact: true }).click()
  await expect(living.getByText('Panorámica validada.', { exact: true })).toBeVisible()
  await living.getByRole('button', { name: 'Ver panorama de Living', exact: true }).click()
  await expect(living.locator('.viewer-frame')).toHaveAttribute('data-status', 'ready')
  await expect(living.locator('canvas')).toHaveCount(1)
  await living.getByRole('button', { name: 'Cerrar panorama de Living', exact: true }).click()
  await page.getByRole('button', { name: 'Subir Cocina', exact: true }).click()
  await expect(page.locator('.scene-items li').first()).toContainText('Cocina')
  await page.getByRole('button', { name: 'Usar Cocina como inicial', exact: true }).click()
  await expect(page.locator('.scene-items li').first()).toContainText('Ambiente inicial')
  await page.getByRole('button', { name: 'Editar Living', exact: true }).click()
  await page.getByLabel('Nombre del ambiente', { exact: true }).fill('Living grande')
  await page.getByRole('button', { name: 'Guardar ambiente', exact: true }).click()
  await expect(page.locator('.scene-items')).toContainText('Living grande')
  await expect(page.locator('.scene-items').getByText('Panorámica validada.', { exact: true })).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('workspace.png'), fullPage: true })
  await page.reload()
  await navigate(page, 'Mis recorridos')
  await page.getByRole('button', { name: `Abrir ${title}`, exact: true }).click()
  await expect(page.locator('.scene-items li').first()).toContainText('Cocina')
  await expect(page.locator('.scene-items')).toContainText('Living grande')
  page.on('dialog', (dialog) => dialog.accept())
  await page.getByRole('button', { name: 'Eliminar Cocina', exact: true }).click()
  await expect(page.locator('.scene-items li')).toHaveCount(1)
  await expect(page.locator('.scene-items')).toContainText('Ambiente inicial')
  await page.getByRole('button', { name: 'Eliminar recorrido', exact: true }).click()
  await expect(page.getByRole('button', { name: `Abrir ${title}`, exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Cerrar sesión', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Ingresar', exact: true })).toBeVisible()
  await page.getByLabel('Email', { exact: true }).fill(email)
  await page.getByLabel('Contraseña', { exact: true }).fill('Test-password-123!')
  await page.getByRole('button', { name: 'Ingresar', exact: true }).click()
  await navigate(page, 'Mis recorridos')
  await expect(page.getByRole('heading', { name: 'Mis recorridos', exact: true })).toBeVisible()
})

test('conecta ambientes, guarda orientación, edita puntos y previsualiza tras recarga', async ({ page, browser }, testInfo) => {
  test.skip(process.env.TEST_API !== '1', 'Necesita la API y base temporal del runner backend')
  test.setTimeout(60_000)
  page.setDefaultTimeout(10_000)
  const title = `Recorrido conectado ${testInfo.project.name} ${Date.now()}`
  await page.goto('/')
  await page.getByRole('button', { name: 'Crear una cuenta', exact: true }).click()
  await page.getByLabel('Email', { exact: true }).fill(`editor-${testInfo.project.name}-${Date.now()}@example.com`)
  await page.getByLabel('Contraseña', { exact: true }).fill('Test-password-123!')
  await page.getByRole('button', { name: 'Registrarme', exact: true }).click()
  await navigate(page, 'Mis recorridos')
  await page.getByLabel('Título', { exact: true }).fill(title)
  await page.getByRole('button', { name: 'Crear recorrido', exact: true }).click()
  await page.getByRole('button', { name: `Abrir ${title}`, exact: true }).click()
  for (const name of ['Living', 'Cocina']) {
    await page.getByLabel('Nombre del ambiente', { exact: true }).fill(name)
    await page.getByRole('button', { name: 'Agregar ambiente', exact: true }).click()
    await expect(page.getByLabel('Nombre del ambiente', { exact: true })).toHaveValue('')
    const item = page.locator('.scene-items li').filter({ has: page.getByRole('button', { name: `Editar ${name}`, exact: true }) })
    await item.getByLabel(`Panorámica JPEG para ${name}`, { exact: true }).setInputFiles(process.env.TEST_PANORAMA_FILE!)
    await item.getByRole('button', { name: 'Subir panorámica', exact: true }).click()
    await expect(item.getByText('Panorámica validada.', { exact: true })).toBeVisible()
  }
  await page.getByRole('button', { name: 'Conectar Living', exact: true }).click()
  const editor = page.getByRole('region', { name: 'Editor del recorrido', exact: true })
  const frame = editor.locator('.viewer-frame')
  await expect(frame).toHaveAttribute('data-status', 'ready')
  const panorama = editor.getByTestId('panorama')
  await panorama.scrollIntoViewIfNeeded()
  const bounds = (await panorama.boundingBox())!
  await page.mouse.move(bounds.x + bounds.width * .6, bounds.y + bounds.height * .5)
  await page.mouse.down()
  await page.mouse.move(bounds.x + bounds.width * .4, bounds.y + bounds.height * .5, { steps: 8 })
  await page.mouse.up()
  await page.waitForTimeout(250)
  await editor.getByRole('button', { name: 'Vista amplia', exact: true }).click()
  await editor.getByRole('button', { name: 'Guardar vista actual como inicial', exact: true }).click()
  await expect(frame).toHaveAttribute('data-status', 'ready')
  // La orientación se guarda en API y vuelve al formulario al salir del editor.
  await editor.getByRole('button', { name: 'Cerrar editor', exact: true }).click()
  await page.getByRole('button', { name: 'Editar Living', exact: true }).click()
  await page.getByText('Vista inicial · opcional', { exact: true }).click()
  expect(Math.abs(Number(await page.getByLabel('Yaw (°)', { exact: true }).inputValue()))).toBeGreaterThan(1)
  await expect(page.getByLabel('Campo de visión (°)', { exact: true })).toHaveValue('110')
  await page.getByRole('button', { name: 'Cancelar edición', exact: true }).click()
  await page.getByRole('button', { name: 'Conectar Living', exact: true }).click()
  await expect(frame).toHaveAttribute('data-status', 'ready')
  async function newPoint(label: string, destination?: string) {
    if (destination) {
      const button = editor.getByRole('button', { name: 'Ubicar punto', exact: true })
      if (await button.getAttribute('aria-pressed') !== 'true') await button.click()
      await panorama.click({ position: { x: 120, y: 100 } })
    } else await editor.getByRole('button', { name: 'Nuevo punto en el centro', exact: true }).click()
    await editor.getByLabel('Etiqueta del punto', { exact: true }).fill(label)
    if (destination) await editor.getByRole('combobox', { name: 'Ambiente de destino', exact: true }).selectOption({ label: destination })
    else {
      await editor.getByRole('combobox', { name: 'Tipo de punto', exact: true }).selectOption('info')
      await editor.getByLabel('Texto informativo', { exact: true }).fill('<b>Ventana al patio</b>')
    }
    // Ubicación visible y reproducible para probar el clic sobre el hotspot.
    await editor.getByText('Ajustar coordenadas manualmente', { exact: true }).click()
    await editor.getByLabel('Yaw del punto (°)', { exact: true }).fill(destination ? '0' : '30')
    await editor.getByLabel('Pitch del punto (°)', { exact: true }).fill('0')
    await editor.getByRole('button', { name: 'Guardar punto', exact: true }).click()
    await expect(editor.locator('.saved-hotspots')).toContainText(label)
    await expect(frame).toHaveAttribute('data-status', 'ready')
  }
  await newPoint('Ir a Cocina', 'Cocina')
  await editor.getByRole('button', { name: 'Ir: Ir a Cocina', exact: true }).click()
  await expect(editor.getByRole('heading', { name: 'Ambiente actual: Cocina', exact: true })).toBeVisible()
  await expect(frame).toHaveAttribute('data-status', 'ready')
  await newPoint('Volver al Living', 'Living')
  await editor.getByRole('button', { name: 'Volver al Living', exact: true }).click()
  await expect(editor.getByRole('heading', { name: 'Ambiente actual: Living', exact: true })).toBeVisible()
  await expect(frame).toHaveAttribute('data-status', 'ready')
  await newPoint('Ventana')
  await editor.getByRole('button', { name: 'Editar punto Ventana', exact: true }).click()
  await editor.getByLabel('Etiqueta del punto', { exact: true }).fill('Luz natural')
  await editor.getByRole('button', { name: 'Guardar punto', exact: true }).click()
  await expect(editor.locator('.saved-hotspots')).toContainText('Luz natural')
  await editor.getByRole('button', { name: 'Cerrar editor', exact: true }).click()
  await page.reload()
  await navigate(page, 'Mis recorridos')
  await page.getByRole('button', { name: `Abrir ${title}`, exact: true }).click()
  await page.getByRole('button', { name: 'Previsualizar recorrido', exact: true }).click()
  const preview = page.getByRole('region', { name: 'Previsualización privada', exact: true })
  await expect(preview.locator('.viewer-frame')).toHaveAttribute('data-status', 'ready')
  await preview.getByRole('button', { name: 'Luz natural', exact: true }).click()
  await expect(preview.locator('.information')).toContainText('<b>Ventana al patio</b>')
  await expect(preview.locator('.information b')).toHaveCount(0)
  await preview.getByRole('button', { name: 'Ir a Cocina', exact: true }).click()
  await expect(preview.getByRole('heading', { name: 'Ambiente actual: Cocina', exact: true })).toBeVisible()
  await expect(preview.locator('.viewer-frame')).toHaveAttribute('data-status', 'ready')
  await preview.getByRole('button', { name: 'Volver al Living', exact: true }).click()
  await expect(preview.getByRole('heading', { name: 'Ambiente actual: Living', exact: true })).toBeVisible()
  await expect(preview.locator('.viewer-frame')).toHaveAttribute('data-status', 'ready')
  await page.screenshot({ path: testInfo.outputPath('connected-preview.png'), fullPage: true })
  await preview.getByRole('button', { name: 'Cerrar previsualización', exact: true }).click()
  await page.getByRole('button', { name: 'Conectar Living', exact: true }).click()
  await expect(editor.locator('.saved-hotspots')).toContainText('Luz natural')
  page.once('dialog', (dialog) => dialog.accept())
  await editor.getByRole('button', { name: 'Eliminar punto Luz natural', exact: true }).click()
  await expect(editor.locator('.saved-hotspots')).not.toContainText('Luz natural')
  await editor.getByRole('button', { name: 'Cerrar editor', exact: true }).click()
  const publication = page.getByRole('region', { name: 'Publicación', exact: true })
  page.once('dialog', (dialog) => dialog.accept())
  await publication.getByRole('button', { name: 'Publicar recorrido', exact: true }).click()
  await expect(publication.getByText('Versión 1 publicada.', { exact: true })).toBeVisible()
  await expect(page.getByLabel('Slug', { exact: true })).toHaveAttribute('readonly', '')
  const publicUrl = await publication.getByLabel('Enlace del recorrido', { exact: true }).inputValue()
  const anonymous = await browser.newContext({ viewport: testInfo.project.use.viewport, isMobile: testInfo.project.use.isMobile,
    hasTouch: testInfo.project.use.hasTouch })
  try {
    const visitor = await anonymous.newPage()
    const requests: string[] = []
    visitor.on('request', (request) => { if (request.url().includes('/api/v1/')) requests.push(request.url()) })
    await visitor.goto(publicUrl)
    await expect(visitor.getByRole('heading', { name: title, exact: true })).toBeVisible()
    await expect(visitor.locator('.viewer-frame')).toHaveAttribute('data-status', 'ready')
    expect(requests.every((url) => new URL(url).pathname.startsWith('/api/v1/public/'))).toBe(true)
    await visitor.getByRole('button', { name: 'Ir a Cocina', exact: true }).click()
    await expect(visitor.getByRole('heading', { name: 'Cocina', exact: true })).toBeVisible()
    await expect(visitor.locator('.viewer-frame')).toHaveAttribute('data-status', 'ready')
    await visitor.getByRole('button', { name: 'Volver al Living', exact: true }).click()
    await expect(visitor.getByRole('heading', { name: 'Living', exact: true })).toBeVisible()
    await expect(visitor.locator('.viewer-frame')).toHaveAttribute('data-status', 'ready')
    await visitor.screenshot({ path: testInfo.outputPath('public-tour.png'), fullPage: true })
    await page.locator('#datos summary').click()
    await page.getByLabel('Título', { exact: true }).fill(`${title} actualizado`)
    await page.getByRole('button', { name: 'Guardar información', exact: true }).click()
    await expect(publication.getByText(/Cambios pendientes:/)).toBeVisible()
    await visitor.reload()
    await expect(visitor.getByRole('heading', { name: title, exact: true })).toBeVisible()
    page.once('dialog', (dialog) => dialog.accept())
    await publication.getByRole('button', { name: 'Publicar cambios', exact: true }).click()
    await expect(publication.getByText('Versión 2 publicada.', { exact: true })).toBeVisible()
    await visitor.reload()
    await expect(visitor.getByRole('heading', { name: `${title} actualizado`, exact: true })).toBeVisible()
    page.once('dialog', (dialog) => dialog.accept())
    await publication.getByRole('button', { name: 'Despublicar recorrido', exact: true }).click()
    await expect(publication.getByText('El recorrido todavía no está publicado.', { exact: true })).toBeVisible()
    await visitor.reload()
    await expect(visitor.getByRole('heading', { name: 'Recorrido no disponible', exact: true })).toBeVisible()
  } finally { await anonymous.close() }
  let confirmation = ''
  page.once('dialog', (dialog) => { confirmation = dialog.message(); void dialog.accept() })
  await page.getByRole('button', { name: 'Eliminar Cocina', exact: true }).click()
  await expect(page.locator('.scene-items li')).toHaveCount(1)
  expect(confirmation).toContain('1 conexiones')
})
