import { expect, test } from '@playwright/test'

test('administración consulta usuarios registrados y las otras cuentas no acceden', async ({ page, browser, baseURL }, testInfo) => {
  test.skip(process.env.TEST_API !== '1' || process.env.AUTH_REQUIRE_VERIFIED_EMAIL === 'true', 'Requiere API temporal y administrador de prueba')
  page.setDefaultTimeout(10_000)
  const email = `directorio-${testInfo.project.name}-${Date.now()}@example.com`
  await page.goto('/studio')
  await page.getByRole('button', { name: 'Crear una cuenta', exact: true }).click()
  await page.getByLabel('Email', { exact: true }).fill(email)
  await page.getByLabel('Contraseña', { exact: true }).fill('Test-password-123!')
  await page.getByRole('button', { name: 'Registrarme', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Mi cuenta', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Usuarios registrados', exact: true })).toHaveCount(0)
  await page.goto('/studio/usuarios')
  await expect(page.getByRole('alert')).toContainText('Acceso reservado a administración')
  const rejected = await page.request.get('http://127.0.0.1:8002/api/v1/admin/accounts')
  expect(rejected.status()).toBe(403)
  const context = await browser.newContext({ baseURL, viewport: page.viewportSize() || undefined })
  try {
    const admin = await context.newPage()
    await admin.goto('/studio')
    await admin.getByLabel('Email', { exact: true }).fill(process.env.TEST_ADMIN_EMAIL!)
    await admin.getByLabel('Contraseña', { exact: true }).fill('Test-password-123!')
    await admin.getByRole('button', { name: 'Ingresar', exact: true }).click()
    await expect(admin.getByRole('button', { name: 'Mi cuenta', exact: true })).toBeVisible()
    const menu = admin.getByRole('button', { name: 'Abrir menú', exact: true })
    if (await menu.isVisible()) await menu.click()
    const directoryButton = admin.getByRole('button', { name: 'Usuarios registrados', exact: true, includeHidden: true })
    await directoryButton.click()
    await expect(directoryButton).toHaveAttribute('aria-current', 'page')
    await expect(admin).toHaveURL(/\/studio\/usuarios/)
    await expect(admin.getByRole('heading', { name: 'Usuarios registrados', exact: true })).toBeVisible()
    await expect(admin.getByRole('table', { name: 'Usuarios registrados', exact: true })).toContainText(email)
    await admin.getByLabel('Buscar cuenta', { exact: true }).fill(email)
    await admin.getByRole('button', { name: 'Buscar', exact: true }).click()
    await expect(admin.getByRole('status')).toHaveText('1 cuenta encontrada')
    await expect(admin.getByRole('table').getByRole('row')).toHaveCount(2)
    await admin.reload()
    await expect(admin.getByRole('status')).toHaveText('1 cuenta encontrada')
    await expect(admin.getByLabel('Buscar cuenta', { exact: true })).toHaveValue(email)
    await admin.getByLabel('Buscar cuenta', { exact: true }).fill('no-existe-este-email')
    await admin.getByRole('button', { name: 'Buscar', exact: true }).click()
    await expect(admin.getByRole('status')).toHaveText('0 cuentas encontradas')
    await admin.getByRole('button', { name: 'Atrás', exact: true }).click()
    await expect(admin.getByRole('status')).toHaveText('1 cuenta encontrada')
    expect(await admin.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await admin.screenshot({ path: testInfo.outputPath('usuarios-registrados.png') })
  } finally { await context.close() }
})
