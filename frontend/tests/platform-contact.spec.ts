import { expect, test } from '@playwright/test'

test('contacto del dueño está en el inicio con formulario y WhatsApp sin registrarse', async ({ page }, testInfo) => {
  test.skip(process.env.TEST_API !== '1', 'Requiere API y PostgreSQL temporal')
  test.setTimeout(60_000)
  const email = `consulta-${testInfo.project.name}-${Date.now()}@example.com`
  const message = 'Quiero conocer cómo funciona Vision360 para mi estudio.'
  await page.goto('/inicio')
  const whatsapp = page.getByRole('link', { name: 'Consultar a Emiliano por WhatsApp', exact: true })
  await expect(whatsapp).toBeInViewport({ ratio: 1 })
  const whatsappUrl = new URL((await whatsapp.getAttribute('href'))!)
  expect(whatsappUrl.hostname).toBe('wa.me')
  expect(whatsappUrl.pathname).toBe('/5491170612602')
  await expect(whatsapp).toHaveAttribute('target', '_blank')
  await page.getByRole('link', { name: 'Contacto', exact: true }).click()
  const form = page.getByRole('form', { name: 'Consultar sobre Vision360', exact: true })
  await expect(form).toBeVisible()
  await expect(page.getByRole('form', { name: 'Solicitar digitalización', exact: true })).toHaveCount(0)
  await form.getByLabel('Email de contacto', { exact: true }).fill('no-es-un-email')
  await form.getByLabel('Teléfono de contacto', { exact: true }).fill('letras')
  await form.getByLabel('Tu consulta', { exact: true }).fill(message)
  expect(await form.evaluate(element => (element as HTMLFormElement).checkValidity())).toBe(false)
  await form.getByLabel('Email de contacto', { exact: true }).fill(email)
  await form.getByLabel('Teléfono de contacto', { exact: true }).fill('11 2345-6789')
  expect(await form.evaluate(element => (element as HTMLFormElement).checkValidity())).toBe(true)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await expect(page.getByRole('navigation', { name: 'Navegación comercial', exact: true })).toHaveCount(1)
  await form.scrollIntoViewIfNeeded()
  await page.screenshot({ path: testInfo.outputPath('contacto-inicio.png') })
  const sent = page.waitForResponse(response => response.url().endsWith('/platform-contact') && response.request().method() === 'POST')
  await form.getByRole('button', { name: 'Enviar consulta', exact: true }).click()
  const response = await sent
  expect(response.status()).toBe(201)
  const receipt = await response.json()
  await expect(page.getByRole('heading', { name: 'Tu consulta quedó registrada.', exact: true })).toBeVisible()
  await page.goto('/studio')
  await expect(page.getByRole('form', { name: 'Consultar sobre Vision360', exact: true })).toHaveCount(0)
  await expect(page.getByText('Cómo protegemos tu cuenta y tus datos', { exact: true })).toHaveCount(0)
  await page.getByLabel('Email', { exact: true }).fill(process.env.TEST_ADMIN_EMAIL!)
  await page.getByLabel('Contraseña', { exact: true }).fill('Test-password-123!')
  await page.getByRole('button', { name: 'Ingresar', exact: true }).click()
  await expect(page.getByRole('link', { name: 'Mi cuenta', exact: true })).toBeVisible()
  const menu = page.getByRole('button', { name: 'Abrir menú', exact: true })
  if (await menu.isVisible()) await menu.click()
  const inboxButton = page.getByRole('link', { name: 'Consultas del sistema', exact: true, includeHidden: true })
  await inboxButton.click()
  await expect(inboxButton).toHaveAttribute('aria-current', 'page')
  await expect(page).toHaveURL(/\/studio\/consultas/)
  await page.getByLabel('Buscar consulta', { exact: true }).fill(email)
  await page.getByRole('button', { name: 'Buscar', exact: true }).click()
  await expect(page.getByRole('status')).toHaveText('Consultas encontradas: 1')
  await page.locator('summary').filter({ hasText: email }).click()
  await expect(page.getByRole('link', { name: 'Llamar', exact: true })).toHaveAttribute('href', 'tel:1123456789')
  await expect(page.getByText(message, { exact: true })).toBeVisible()
  await expect(page.getByText(`Referencia: ${receipt.id}`, { exact: true })).toBeVisible()
  await expect(page.getByRole('link', { name: 'Responder por email', exact: true })).toHaveAttribute('href', `mailto:${encodeURIComponent(email)}`)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: testInfo.outputPath('consultas-administracion.png') })
  await page.getByRole('combobox', { name: 'Idioma', exact: true }).selectOption('pt-BR')
  await expect(page.getByRole('heading', { name: 'Consultas sobre o sistema', exact: true })).toBeVisible()
  await expect(page.getByRole('link', { name: 'Ligar', exact: true })).toBeVisible()
  await expect(page.getByText(message, { exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Consultas sobre o sistema', exact: true })).toBeVisible()
  await expect(page.getByLabel('Buscar consulta', { exact: true })).toHaveValue(email)
  await expect(page.getByRole('status')).toHaveText('Consultas encontradas: 1')
  await page.getByRole('combobox', { name: 'Idioma', exact: true }).selectOption('es')
  await page.getByRole('button', { name: 'Cerrar sesión', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Ingresar', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Crear una cuenta', exact: true }).click()
  await page.getByLabel('Email', { exact: true }).fill(`usuario-${email}`)
  await page.getByLabel('Contraseña', { exact: true }).fill('Test-password-123!')
  await page.getByRole('button', { name: 'Registrarme', exact: true }).click()
  await expect(page.getByRole('link', { name: 'Mi cuenta', exact: true })).toBeVisible()
  await expect(page.getByRole('link', { name: 'Consultas del sistema', exact: true })).toHaveCount(0)
  await page.goto('/studio/consultas')
  await expect(page.getByRole('alert')).toContainText('Acceso reservado a administración')
  expect((await page.request.get('http://127.0.0.1:8002/api/v1/admin/platform-contacts')).status()).toBe(403)
})
