import { expect, test } from '@playwright/test'

test('contacto del dueño está en el inicio con formulario y WhatsApp sin registrarse', async ({ page }, testInfo) => {
  test.skip(process.env.TEST_API !== '1', 'Requiere API y PostgreSQL temporal')
  await page.goto('/inicio')
  const whatsapp = page.getByRole('link', { name: 'Consultar a Emiliano por WhatsApp', exact: true })
  await expect(whatsapp).toBeInViewport({ ratio: 1 })
  const whatsappUrl = new URL((await whatsapp.getAttribute('href'))!)
  expect(whatsappUrl.hostname).toBe('wa.me')
  expect(whatsappUrl.pathname).toBe('/5491170612602')
  await expect(whatsapp).toHaveAttribute('target', '_blank')
  await page.getByRole('link', { name: 'Contacto', exact: true }).click()
  const form = page.getByRole('form', { name: 'Consultar sobre Vision360', exact: true })
  await expect(form).toBeVisible()
  await expect(page.getByRole('form', { name: 'Solicitar digitalización', exact: true })).toHaveCount(0)
  await form.getByLabel('Email de contacto', { exact: true }).fill('no-es-un-email')
  await form.getByLabel('Teléfono de contacto', { exact: true }).fill('letras')
  await form.getByLabel('Tu consulta', { exact: true }).fill('Quiero conocer cómo funciona Vision360 para mi estudio.')
  expect(await form.evaluate(element => (element as HTMLFormElement).checkValidity())).toBe(false)
  await form.getByLabel('Email de contacto', { exact: true }).fill('consulta@example.com')
  await form.getByLabel('Teléfono de contacto', { exact: true }).fill('11 2345-6789')
  expect(await form.evaluate(element => (element as HTMLFormElement).checkValidity())).toBe(true)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await expect(page.getByRole('navigation', { name: 'Navegación comercial', exact: true })).toHaveCount(1)
  await form.scrollIntoViewIfNeeded()
  await page.screenshot({ path: testInfo.outputPath('contacto-inicio.png') })
  const sent = page.waitForResponse(response => response.url().endsWith('/platform-contact') && response.request().method() === 'POST')
  await form.getByRole('button', { name: 'Enviar consulta', exact: true }).click()
  expect((await sent).status()).toBe(201)
  await expect(page.getByRole('heading', { name: 'Tu consulta quedó registrada.', exact: true })).toBeVisible()
  await page.goto('/studio')
  await expect(page.getByRole('form', { name: 'Consultar sobre Vision360', exact: true })).toHaveCount(0)
  await expect(page.getByText('Cómo protegemos tu cuenta y tus datos', { exact: true })).toHaveCount(0)
})
