import { expect, test } from '@playwright/test'
import { navigate } from './navigationHelpers'

test('historial conserva secciones filtros trabajos y pasos y protege cambios sin guardar', async ({ page }, testInfo) => {
  test.skip(process.env.TEST_API !== '1', 'Requiere API y PostgreSQL temporal')
  test.setTimeout(90_000)
  page.setDefaultTimeout(10_000)
  const stamp = `${testInfo.project.name}-${Date.now()}`
  const company = `Remax ${stamp}`
  const title = `Visita ${stamp}`
  await page.goto('/studio')
  await page.getByRole('button', { name: 'Crear una cuenta', exact: true }).click()
  await page.getByLabel('Email', { exact: true }).fill(`history-${stamp}@example.com`)
  await page.getByLabel('Contraseña', { exact: true }).fill('Test-password-123!')
  await page.getByRole('button', { name: 'Registrarme', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Trabajos', exact: true })).toBeVisible()
  const toolbar = page.getByRole('navigation', { name: 'Historial de navegación', exact: true })
  await expect(toolbar.getByRole('button', { name: 'Atrás', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: 'Editar estudio', exact: true }).click()
  await page.getByLabel('Nombre del estudio', { exact: true }).fill('Nombre sin guardar')
  page.once('dialog', (dialog) => dialog.dismiss())
  await navigate(page, 'Organizaciones')
  await expect(page.getByLabel('Nombre del estudio', { exact: true })).toHaveValue('Nombre sin guardar')
  page.once('dialog', (dialog) => dialog.accept())
  await navigate(page, 'Organizaciones')
  await expect(page.getByLabel('Nombre del estudio', { exact: true })).toHaveCount(0)
  await expect(page.getByRole('heading', { name: 'Mi estudio', exact: true })).toBeVisible()
  await expect(page).toHaveURL(/\/studio\/organizaciones\?/)
  await page.getByLabel('Nombre de la organización', { exact: true }).fill(company)
  await page.getByRole('button', { name: 'Crear organización', exact: true }).click()
  await expect(page.getByRole('heading', { name: company, exact: true })).toBeVisible()
  await page.getByLabel('Nombre de la organización', { exact: true }).fill('Otro cliente')
  await page.getByRole('button', { name: 'Crear organización', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Otro cliente', exact: true })).toBeVisible()
  await navigate(page, 'Particulares')
  await page.goBack()
  await expect(page.getByRole('heading', { name: company, exact: true })).toBeVisible()
  await toolbar.getByRole('button', { name: 'Adelante', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Particulares', exact: true })).toBeVisible()
  // A new branch discards the old forward destination, as in a normal browser.
  await toolbar.getByRole('button', { name: 'Atrás', exact: true }).click()
  await navigate(page, 'Gestionar clientes')
  await expect(toolbar.getByRole('button', { name: 'Adelante', exact: true })).toBeDisabled()
  await page.getByLabel('Buscar cliente', { exact: true }).fill('Remax')
  await page.getByRole('combobox', { name: 'Tipo de cliente', exact: true }).selectOption('organization')
  const filteredUrl = page.url()
  await page.getByRole('button', { name: `Ver recorridos de ${company}`, exact: true }).click()
  await expect(page.getByRole('heading', { name: `Recorridos de ${company}`, exact: true })).toBeVisible()
  await page.goBack()
  await expect(page).toHaveURL(filteredUrl)
  await expect(page.getByLabel('Buscar cliente', { exact: true })).toHaveValue('Remax')
  await expect(page.getByRole('combobox', { name: 'Tipo de cliente', exact: true })).toHaveValue('organization')
  await page.goForward()
  await page.reload()
  await expect(page.getByRole('heading', { name: `Recorridos de ${company}`, exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Nuevo trabajo', exact: true }).click()
  await expect(page).toHaveURL(/nuevo=1/)
  await page.getByLabel('Nombre del trabajo', { exact: true }).fill(title)
  const formUrl = page.url()
  page.once('dialog', (dialog) => dialog.dismiss())
  await navigate(page, 'Gestionar clientes')
  await expect(page).toHaveURL(formUrl)
  await expect(page.getByLabel('Nombre del trabajo', { exact: true })).toHaveValue(title)
  // A cancelled native Back must restore its entry without destroying Forward.
  page.once('dialog', (dialog) => dialog.dismiss())
  await page.goBack()
  await expect(page).toHaveURL(formUrl)
  await expect(page.getByLabel('Nombre del trabajo', { exact: true })).toHaveValue(title)
  await page.getByLabel('Localidad del trabajo', { exact: true }).fill('Buenos Aires')
  await page.getByLabel('Superficie aproximada (m²)', { exact: true }).fill('80')
  await page.getByLabel('Cantidad de ambientes', { exact: true }).fill('3')
  await page.getByRole('button', { name: 'Guardar y abrir trabajo', exact: true }).click()
  await expect(page.getByRole('heading', { name: title, exact: true })).toBeVisible()
  const createdUrl = page.url()
  await page.goBack()
  await expect(page.getByRole('heading', { name: `Recorridos de ${company}`, exact: true })).toBeVisible()
  await page.goForward()
  await expect(page).toHaveURL(createdUrl)
  await expect(page.getByRole('heading', { name: title, exact: true })).toBeVisible()
  const steps = page.getByRole('group', { name: 'Pasos del trabajo', exact: true })
  await steps.getByRole('button', { name: '3 Fotos', exact: true }).click()
  await expect(page).toHaveURL(/paso=photos/)
  const photosUrl = page.url()
  await page.reload()
  await expect(page.getByRole('heading', { name: title, exact: true })).toBeVisible()
  await expect(steps.getByRole('button', { name: '3 Fotos', exact: true })).toHaveAttribute('aria-current', 'step')
  await steps.getByRole('button', { name: '2 Visita', exact: true }).click()
  await expect(page).toHaveURL(/paso=visit/)
  const visitUrl = page.url()
  await page.getByLabel('Notas operativas', { exact: true }).fill('Nota que todavía no guardé')
  page.once('dialog', (dialog) => dialog.dismiss())
  await toolbar.getByRole('button', { name: 'Atrás', exact: true }).click()
  await expect(page).toHaveURL(visitUrl)
  await expect(page.getByLabel('Notas operativas', { exact: true })).toHaveValue('Nota que todavía no guardé')
  page.once('dialog', (dialog) => dialog.accept())
  await toolbar.getByRole('button', { name: 'Atrás', exact: true }).click()
  await expect(page).toHaveURL(photosUrl)
  await expect(steps.getByRole('button', { name: '3 Fotos', exact: true })).toHaveAttribute('aria-current', 'step')
  await page.goForward()
  await expect(page).toHaveURL(visitUrl)
  await expect(page.getByLabel('Notas operativas', { exact: true })).not.toHaveValue('Nota que todavía no guardé')
  await navigate(page, 'Organizaciones')
  await page.getByRole('button', { name: `Abrir organización ${company}`, exact: true }).click()
  await page.getByRole('button', { name: `Abrir ${title}`, exact: true }).click()
  await expect(page).toHaveURL(/recorrido=/)
  const tourUrl = page.url()
  await page.reload()
  await expect(page.getByRole('heading', { name: title, exact: true })).toBeVisible()
  await toolbar.getByRole('button', { name: 'Atrás', exact: true }).click()
  await expect(page.getByRole('heading', { name: `Recorridos de ${company}`, exact: true })).toBeVisible()
  await toolbar.getByRole('button', { name: 'Adelante', exact: true }).click()
  await expect(page).toHaveURL(tourUrl)
  await expect(page.getByRole('heading', { name: title, exact: true })).toBeVisible()
  await page.getByLabel('Organización activa', { exact: true }).selectOption({ label: 'Otro cliente' })
  await expect(page.getByRole('heading', { name: 'Recorridos de Otro cliente', exact: true })).toBeVisible()
  expect(new URL(page.url()).searchParams.has('recorrido')).toBe(false)
  await page.goBack()
  await expect(page).toHaveURL(tourUrl)
  await expect(page.getByRole('heading', { name: title, exact: true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.screenshot({ path: testInfo.outputPath('historial-recorrido.png'), fullPage: true })
})
