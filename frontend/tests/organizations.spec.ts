import { expect, test } from '@playwright/test'
import { navigate } from './navigationHelpers'

test('fichas de clientes permiten crear, editar y quitar datos sin duplicar registros', async ({ page }, testInfo) => {
  test.skip(process.env.TEST_API !== '1', 'Requiere API y PostgreSQL temporal')
  test.setTimeout(90_000)
  const stamp = `${testInfo.project.name}-${Date.now()}`
  await page.goto('/studio')
  await page.getByRole('button', { name: 'Crear una cuenta', exact: true }).click()
  await page.getByLabel('Email', { exact: true }).fill(`profiles-${stamp}@example.com`)
  await page.getByLabel('Contraseña', { exact: true }).fill('Test-password-123!')
  await page.getByRole('button', { name: 'Registrarme', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Trabajos', exact: true })).toBeVisible()
  for (const individual of [false, true]) {
    const section = individual ? 'Particulares' : 'Organizaciones'
    const name = `${individual ? 'Persona' : 'Empresa'} ${stamp}`
    const renamed = `${name} editada`
    await navigate(page, section)
    const create = page.getByRole('form', { name: individual ? 'Crear particular' : 'Crear organización', exact: true })
    await create.getByLabel(individual ? 'Nombre del particular' : 'Nombre de la organización', { exact: true }).fill(name)
    await create.getByLabel('Email', { exact: true }).fill('contacto@example.com')
    await create.getByLabel('Teléfono', { exact: true }).fill('+54 11 12345678')
    await create.getByLabel('Localidad', { exact: true }).fill('Palermo')
    if (!individual) {
      await create.getByLabel('Razón social', { exact: true }).fill('Empresa SA')
      await create.getByLabel('Responsable', { exact: true }).fill('Ana Pérez')
    }
    await create.getByRole('button', { name: individual ? 'Crear particular' : 'Crear organización', exact: true }).click()
    await page.getByRole('button', { name: `Ver ficha de ${name}`, exact: true }).click()
    const profile = page.getByRole('region', { name: 'Ficha del cliente', exact: true })
    await expect(profile.getByText('contacto@example.com', { exact: true })).toBeVisible()
    if (!individual) await expect(profile.getByText('Ana Pérez', { exact: true })).toBeVisible()
    await profile.getByRole('button', { name: 'Editar información', exact: true }).click()
    await profile.getByLabel('Email', { exact: true }).fill('descartar@example.com')
    page.once('dialog', (dialog) => dialog.dismiss())
    await profile.getByRole('button', { name: 'Volver a la lista', exact: true }).click()
    await expect(profile.getByLabel('Email', { exact: true })).toHaveValue('descartar@example.com')
    page.once('dialog', (dialog) => dialog.accept())
    await profile.getByRole('button', { name: 'Cancelar edición', exact: true }).click()
    await expect(profile.getByText('contacto@example.com', { exact: true })).toBeVisible()
    await profile.getByRole('button', { name: 'Editar información', exact: true }).click()
    await profile.getByLabel(individual ? 'Nombre del particular' : 'Nombre de la organización', { exact: true }).fill(renamed)
    await profile.getByLabel('Email', { exact: true }).fill('')
    await profile.getByLabel('Localidad', { exact: true }).fill('Belgrano')
    await profile.getByLabel('Notas internas', { exact: true }).fill('Llamar por la tarde')
    await profile.getByRole('button', { name: 'Guardar cambios', exact: true }).click()
    await expect(profile.getByRole('status')).toHaveText('Datos del cliente guardados.')
    await navigate(page, 'Gestionar clientes')
    const row = page.getByRole('row').filter({ has: page.getByRole('rowheader', { name: renamed, exact: true }) })
    await expect(row).toContainText('Belgrano')
    await expect(row).not.toContainText('contacto@example.com')
    await page.reload()
    await page.getByRole('button', { name: `Ver ficha de ${renamed}`, exact: true }).click()
    await expect(profile.getByText('Llamar por la tarde', { exact: true })).toBeVisible()
    await profile.getByRole('button', { name: 'Editar información', exact: true }).click()
    await profile.getByLabel('Teléfono', { exact: true }).fill('5551234')
    await profile.getByRole('button', { name: 'Guardar cambios', exact: true }).click()
    await expect(profile.getByRole('status')).toHaveText('Datos del cliente guardados.')
    await profile.getByRole('button', { name: 'Volver a la lista', exact: true }).click()
    await expect(row).toContainText('5551234')
    await navigate(page, section)
    await page.getByRole('button', { name: `Ver ficha de ${renamed}`, exact: true }).click()
    await expect(profile.getByText('5551234', { exact: true })).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  }
})

test('organizaciones y particulares agrupan sus recorridos y crean trabajos en el espacio correcto', async ({ page }, testInfo) => {
  test.skip(process.env.TEST_API !== '1', 'Requiere API y PostgreSQL temporal')
  test.setTimeout(60_000)
  page.setDefaultTimeout(10_000)
  const stamp = `${testInfo.project.name}-${Date.now()}`
  const company = `Remax ${stamp}`
  const person = `Fernando ${stamp}`
  await page.goto('/studio')
  await page.getByRole('button', { name: 'Crear una cuenta', exact: true }).click()
  await page.getByLabel('Email', { exact: true }).fill(`directory-${stamp}@example.com`)
  await page.getByLabel('Contraseña', { exact: true }).fill('Test-password-123!')
  await page.getByRole('button', { name: 'Registrarme', exact: true }).click()
  await navigate(page, 'Organizaciones')
  await page.getByLabel('Nombre de la organización', { exact: true }).fill(company)
  await page.getByRole('button', { name: 'Crear organización', exact: true }).click()
  await expect(page.getByRole('status')).toContainText(`${company} se creó correctamente`)
  await expect(page.getByLabel('Nombre de la organización', { exact: true })).toHaveValue('')
  await expect(page.getByRole('heading', { name: `Recorridos de ${company}`, exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: `Abrir organización ${company}`, exact: true }).click()
  await expect(page.getByRole('heading', { name: `Recorridos de ${company}`, exact: true })).toBeVisible()
  await expect(page.getByText('Crear recorrido sin trabajo', { exact: true })).toHaveCount(0)
  async function createWork(title: string, customer: string) {
    await page.getByRole('button', { name: 'Nuevo trabajo', exact: true }).click()
    await expect(page.getByLabel('Nombre del contacto', { exact: true })).toHaveValue(customer)
    await page.getByLabel('Nombre del trabajo', { exact: true }).fill(title)
    await page.getByLabel('Email de contacto', { exact: true }).fill('directory-customer@example.com')
    await page.getByLabel('WhatsApp de contacto', { exact: true }).fill('+54 911 12345678')
    await page.getByLabel('Localidad del trabajo', { exact: true }).fill('Buenos Aires')
    await page.getByLabel('Superficie aproximada (m²)', { exact: true }).fill('80')
    await page.getByLabel('Cantidad de ambientes', { exact: true }).fill('3')
    await page.getByRole('button', { name: 'Guardar y abrir trabajo', exact: true }).click()
    await expect(page.getByRole('heading', { name: title, exact: true })).toBeVisible()
  }
  await createWork('Casa Remax 1', company)
  await navigate(page, 'Organizaciones')
  await page.getByRole('button', { name: `Abrir organización ${company}`, exact: true }).click()
  await createWork('Casa Remax 2', company)
  await navigate(page, 'Particulares')
  await expect(page.getByRole('button', { name: `Abrir organización ${company}`, exact: true })).toHaveCount(0)
  await page.getByLabel('Nombre del particular', { exact: true }).fill(person)
  await page.getByRole('button', { name: 'Crear particular', exact: true }).click()
  await expect(page.getByRole('status')).toContainText(`${person} se creó correctamente`)
  await expect(page.getByLabel('Nombre del particular', { exact: true })).toHaveValue('')
  await expect(page.getByRole('heading', { name: `Recorridos de ${person}`, exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: `Abrir particular ${person}`, exact: true }).click()
  await expect(page.getByRole('heading', { name: `Recorridos de ${person}`, exact: true })).toBeVisible()
  await expect(page.getByText('Crear recorrido sin trabajo', { exact: true })).toHaveCount(0)
  await createWork('Casa particular Fernando', person)
  await navigate(page, 'Organizaciones')
  await expect(page.getByRole('button', { name: `Abrir particular ${person}`, exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: `Abrir organización ${company}`, exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Casa Remax 1', exact: true })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Casa Remax 2', exact: true })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Casa particular Fernando', exact: true })).toHaveCount(0)
  await page.screenshot({ path: testInfo.outputPath('organizacion-recorridos.png'), fullPage: true })
  await navigate(page, 'Gestionar clientes')
  await expect(page.getByRole('rowheader', { name: company, exact: true })).toHaveCount(1)
  await expect(page.getByRole('button', { name: `Ver recorridos de ${company}`, exact: true })).toHaveCount(1)
  await expect(page.getByRole('button', { name: 'Guardar cliente', exact: true })).toHaveCount(0)
  await page.reload()
  await navigate(page, 'Particulares')
  await page.getByRole('button', { name: `Abrir particular ${person}`, exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Casa particular Fernando', exact: true })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Casa Remax 1', exact: true })).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Particulares', exact: true, includeHidden: true })).toHaveAttribute('aria-current', 'page')
  await page.screenshot({ path: testInfo.outputPath('particular-recorridos.png'), fullPage: true })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
})
