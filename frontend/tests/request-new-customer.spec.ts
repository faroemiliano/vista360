import { expect, test, devices } from '@playwright/test'
import { navigate } from './navigationHelpers'

test('registra al cliente nuevo desde la consulta y sigue con el trabajo sin salir de la página', async ({ page, browser, baseURL, isMobile }, testInfo) => {
  test.skip(process.env.TEST_API !== '1', 'Requiere PostgreSQL y API temporal')
  test.setTimeout(60_000)
  page.setDefaultTimeout(10_000)
  const stamp = `${testInfo.project.name}-${Date.now()}`
  const contact = `Contacto nuevo ${stamp}`
  const company = `Empresa nueva ${stamp}`
  await page.goto('/studio')
  await page.getByRole('button', { name: 'Crear una cuenta', exact: true }).click()
  await page.getByLabel('Email', { exact: true }).fill(`new-customer-${stamp}@example.com`)
  await page.getByLabel('Contraseña', { exact: true }).fill('Test-password-123!')
  await page.getByRole('button', { name: 'Registrarme', exact: true }).click()
  await navigate(page, 'Solicitudes web')
  await page.getByRole('button', { name: 'Activar mi formulario', exact: true }).click()
  const link = await page.getByRole('textbox', { name: 'Mi enlace de solicitudes', exact: true }).inputValue()
  const publicContext = await browser.newContext({ ...(isMobile ? devices['Pixel 7'] : {}), baseURL })
  try {
    const visitor = await publicContext.newPage()
    await visitor.goto(link)
    const form = visitor.getByRole('form', { name: 'Solicitar digitalización', exact: true })
    await form.getByLabel('Nombre', { exact: true }).fill(contact)
    await form.getByLabel('Email', { exact: true }).fill('contact-new@example.com')
    await form.getByLabel('WhatsApp', { exact: true }).fill('+54 9 11 1234 5678')
    await form.getByRole('combobox', { name: 'Tipo de propiedad', exact: true }).selectOption('casa')
    await form.getByLabel('Localidad', { exact: true }).fill('Palermo')
    await form.getByLabel('Superficie aproximada (m²)', { exact: true }).fill('90')
    await form.getByLabel('Cantidad de ambientes', { exact: true }).fill('3')
    await form.getByRole('checkbox').check()
    await form.getByRole('button', { name: 'Enviar solicitud de digitalización', exact: true }).click()
    await expect(visitor.getByRole('heading', { name: 'Ya registramos tu consulta.', exact: true })).toBeVisible()
  } finally { await publicContext.close() }
  await page.getByRole('button', { name: 'Actualizar bandeja', exact: true }).click()
  await page.getByRole('heading', { name: contact, exact: true }).click()
  await page.getByRole('button', { name: `Preparar trabajo para ${contact}`, exact: true }).click()
  await page.getByRole('button', { name: 'Nuevo cliente', exact: true }).click()
  const register = page.getByRole('form', { name: 'Registrar cliente desde consulta', exact: true })
  await expect(register.getByLabel('Nombre del particular', { exact: true })).toHaveValue(contact)
  await expect(register.getByLabel('Email del cliente', { exact: true })).toHaveValue('contact-new@example.com')
  await expect(register.getByLabel('Teléfono del cliente', { exact: true })).toHaveValue('+5491112345678')
  await expect(register.getByLabel('Localidad del cliente', { exact: true })).toHaveValue('Palermo')
  if (isMobile) {
    await register.getByRole('combobox', { name: 'Tipo de cliente', exact: true }).selectOption('company')
    await register.getByLabel('Nombre de la empresa', { exact: true }).fill(company)
    await register.getByLabel('Razón social', { exact: true }).fill('Empresa de prueba SRL')
    await expect(register.getByLabel('Responsable', { exact: true })).toHaveValue(contact)
  }
  await page.screenshot({ path: testInfo.outputPath('registrar-desde-consulta.png'), fullPage: true })
  const created = page.waitForResponse(response => response.request().method() === 'POST' && response.url().endsWith('/organizations'))
  await register.getByRole('button', { name: 'Guardar cliente y continuar', exact: true }).click()
  const response = await created
  expect(response.status()).toBe(201)
  const client = await response.json()
  expect(client.name).toBe(isMobile ? company : contact)
  expect(client.kind).toBe(isMobile ? 'company' : 'individual')
  expect(client.email).toBe('contact-new@example.com')
  expect(client.phone).toBe('+5491112345678')
  expect(client.locality).toBe('Palermo')
  expect(new URL(page.url()).pathname).toBe('/studio/solicitudes')
  await expect(page.getByRole('heading', { name: 'Preparar trabajo desde solicitud', exact: true })).toBeVisible()
  const work = page.getByRole('form', { name: 'Preparar trabajo', exact: true })
  await work.getByLabel('Nombre del trabajo', { exact: true }).fill(`Visita nueva ${stamp}`)
  await work.getByRole('button', { name: 'Guardar y abrir trabajo', exact: true }).click()
  await expect(page).toHaveURL(/\/studio\/trabajos\/[a-f\d-]+/)
  await expect(page.getByRole('heading', { name: `Visita nueva ${stamp}`, exact: true })).toBeVisible()
  await navigate(page, 'Gestionar clientes')
  await expect(page.getByRole('rowheader', { name: client.name, exact: true })).toBeVisible()
  await expect(page.getByRole('rowheader', { name: client.name, exact: true })).toHaveCount(1)
})
