import { expect, test } from '@playwright/test'

test('recordatorio del plan aparece la última semana y desaparece después de renovar', async ({ page, browser, baseURL }, testInfo) => {
  test.skip(process.env.TEST_API !== '1' || process.env.AUTH_REQUIRE_VERIFIED_EMAIL === 'true', 'Requiere API temporal')
  test.setTimeout(90_000)
  page.setDefaultTimeout(10_000)
  const email = `recordatorio-${testInfo.project.name}-${Date.now()}@example.com`
  await page.goto('/studio')
  await page.getByRole('button', { name: 'Crear una cuenta', exact: true }).click()
  await page.getByLabel('Email', { exact: true }).fill(email)
  await page.getByLabel('Contraseña', { exact: true }).fill('Test-password-123!')
  await page.getByRole('button', { name: 'Registrarme', exact: true }).click()
  await expect(page.getByRole('link', { name: 'Mi cuenta', exact: true })).toBeVisible()
  await expect(page.getByRole('complementary', { name: 'Recordatorio de vencimiento', exact: true })).toHaveCount(0)
  const adminContext = await browser.newContext({ baseURL, viewport: page.viewportSize() || undefined })
  try {
    const admin = await adminContext.newPage()
    await admin.goto('/studio')
    await admin.getByLabel('Email', { exact: true }).fill(process.env.TEST_ADMIN_EMAIL!)
    await admin.getByLabel('Contraseña', { exact: true }).fill('Test-password-123!')
    await admin.getByRole('button', { name: 'Ingresar', exact: true }).click()
    await expect(admin.getByRole('link', { name: 'Mi cuenta', exact: true })).toBeVisible()
    await admin.goto(`/studio/usuarios?buscar=${encodeURIComponent(email)}`)
    await admin.getByRole('button', { name: `Gestionar plan de ${email}`, exact: true }).click()
    const panel = admin.getByRole('dialog', { name: 'Gestionar plan', exact: true })
    await panel.getByRole('combobox', { name: 'Plan', exact: true }).selectOption('professional')
    await panel.getByRole('combobox', { name: 'Período a habilitar', exact: true }).selectOption('custom')
    await panel.getByLabel('Días del período', { exact: true }).fill('6')
    await panel.getByLabel('Nota administrativa', { exact: true }).fill('Período especial acordado')
    admin.once('dialog', dialog => dialog.accept())
    await panel.getByRole('button', { name: 'Asignar o renovar plan', exact: true }).click()
    await expect(panel.getByRole('status')).toContainText('Plan actualizado')
    await page.reload()
    const reminder = page.getByRole('complementary', { name: 'Recordatorio de vencimiento', exact: true })
    await expect(reminder).toContainText('Te quedan 6 días')
    await expect(reminder.getByRole('link', { name: 'Coordinar renovación', exact: true })).toBeVisible()
    await reminder.getByRole('button', { name: 'Ver mi plan', exact: true }).click()
    const account = page.getByRole('dialog', { name: 'Mi cuenta', exact: true })
    await expect(account.getByRole('link', { name: 'Mi plan', exact: true })).toHaveAttribute('aria-current', 'page')
    await expect(account.getByText('Te quedan 6 días', { exact: true })).toBeVisible()
    await page.screenshot({ path: testInfo.outputPath('dias-restantes.png') })
    await account.getByRole('button', { name: 'Cerrar Mi cuenta', exact: true }).click()
    await panel.getByRole('combobox', { name: 'Período a habilitar', exact: true }).selectOption('monthly')
    await panel.getByLabel('Nota administrativa', { exact: true }).fill('Pago recibido, renovar un mes')
    admin.once('dialog', dialog => dialog.accept())
    await panel.getByRole('button', { name: 'Asignar o renovar plan', exact: true }).click()
    await expect(panel.getByRole('status')).toContainText('Plan actualizado')
    await page.reload()
    await expect(page.getByRole('link', { name: 'Mi cuenta', exact: true })).toBeVisible()
    await expect(reminder).toHaveCount(0)
  } finally { await adminContext.close() }
})
