import { expect, test } from '@playwright/test'
import { navigate } from './navigationHelpers'

test('rutas de fichas y cuenta conservan recarga historial y cambios pendientes', async ({ page, context, browser, baseURL }, testInfo) => {
  test.skip(process.env.TEST_API !== '1', 'Requiere API y PostgreSQL temporal')
  test.setTimeout(90_000)
  page.setDefaultTimeout(10_000)
  const stamp = `${testInfo.project.name}-${Date.now()}`
  const name = `Hotel ${stamp}`
  await page.goto('/studio')
  await page.getByRole('button', { name: 'Crear una cuenta', exact: true }).click()
  await page.getByLabel('Email', { exact: true }).fill(`rutas-${stamp}@example.com`)
  await page.getByLabel('Contraseña', { exact: true }).fill('Test-password-123!')
  await page.getByRole('button', { name: 'Registrarme', exact: true }).click()
  await navigate(page, 'Organizaciones')
  await page.getByLabel('Nombre de la organización', { exact: true }).fill(name)
  await page.getByRole('button', { name: 'Crear organización', exact: true }).click()
  await page.getByRole('link', { name: `Ver ficha de ${name}`, exact: true }).click()
  const profile = page.getByRole('region', { name: 'Ficha del cliente', exact: true })
  await expect(profile.getByRole('heading', { name, exact: true })).toBeVisible()
  await expect(page).toHaveURL(/\/studio\/clientes\/[a-f\d-]{36}\?estudio=/)
  const profileUrl = page.url()
  await page.reload()
  await expect(profile.getByRole('heading', { name, exact: true })).toBeVisible()
  await profile.getByRole('button', { name: 'Editar información', exact: true }).click()
  await profile.getByLabel('Teléfono', { exact: true }).fill('1155551234')
  page.once('dialog', dialog => dialog.dismiss())
  await page.goBack()
  await expect(page).toHaveURL(profileUrl)
  await expect(profile.getByLabel('Teléfono', { exact: true })).toHaveValue('1155551234')
  page.once('dialog', dialog => dialog.accept())
  await page.goBack()
  await expect(page.getByRole('heading', { name: 'Organizaciones', exact: true })).toBeVisible()
  await page.goForward()
  await expect(profile.getByRole('heading', { name, exact: true })).toBeVisible()
  await expect(profile.getByLabel('Teléfono', { exact: true })).toHaveCount(0)
  await profile.getByRole('button', { name: 'Volver a la lista', exact: true }).click()
  const clientLink = page.getByRole('link', { name: `Ver ficha de ${name}`, exact: true })
  await expect(clientLink).toHaveAttribute('href', new URL(profileUrl).pathname + new URL(profileUrl).search)
  // Un clic modificado conserva el comportamiento nativo del navegador.
  const beforeTab = page.url()
  const popupPromise = context.waitForEvent('page')
  await clientLink.dispatchEvent('click', { button: 0, ctrlKey: true, metaKey: true })
  const popup = await popupPromise
  await expect(popup.getByRole('region', { name: 'Ficha del cliente', exact: true })).toBeVisible()
  await expect(page).toHaveURL(beforeTab)
  await popup.close()
  const outsiderContext = await browser.newContext({ baseURL })
  try {
    const outsider = await outsiderContext.newPage()
    await outsider.goto('/studio')
    await outsider.getByRole('button', { name: 'Crear una cuenta', exact: true }).click()
    await outsider.getByLabel('Email', { exact: true }).fill(`otro-estudio-${stamp}@example.com`)
    await outsider.getByLabel('Contraseña', { exact: true }).fill('Test-password-123!')
    await outsider.getByRole('button', { name: 'Registrarme', exact: true }).click()
    await expect(outsider.getByRole('heading', { name: 'Trabajos', exact: true })).toBeVisible()
    await outsider.goto(new URL(profileUrl).pathname)
    await expect(outsider.getByRole('alert')).toHaveText('Cliente no encontrado en este estudio.')
    await expect(outsider.getByRole('heading', { name, exact: true })).toHaveCount(0)
  } finally { await outsiderContext.close() }
  await page.getByRole('link', { name: 'Mi cuenta', exact: true }).click()
  const account = page.getByRole('dialog', { name: 'Mi cuenta', exact: true })
  await expect(page).toHaveURL(/\/mi-cuenta\/perfil\?/)
  await account.getByLabel('Nombre y apellido', { exact: true }).fill('Sin guardar')
  page.once('dialog', dialog => dialog.dismiss())
  await account.getByRole('link', { name: 'Email y contraseña', exact: true }).click()
  await expect(page).toHaveURL(/\/mi-cuenta\/perfil\?/)
  await expect(account.getByLabel('Nombre y apellido', { exact: true })).toHaveValue('Sin guardar')
  page.once('dialog', dialog => dialog.accept())
  await account.getByRole('link', { name: 'Email y contraseña', exact: true }).click()
  await expect(page).toHaveURL(/\/mi-cuenta\/seguridad\?/)
  await page.reload()
  await expect(account.getByRole('link', { name: 'Email y contraseña', exact: true })).toHaveAttribute('aria-current', 'page')
  await account.getByRole('link', { name: 'Mi plan', exact: true }).click()
  await expect(page).toHaveURL(/\/mi-cuenta\/plan\?/)
  await page.goBack()
  await expect(account.getByRole('link', { name: 'Email y contraseña', exact: true })).toHaveAttribute('aria-current', 'page')
  await page.goForward()
  await expect(account.getByRole('link', { name: 'Mi plan', exact: true })).toHaveAttribute('aria-current', 'page')
  await account.getByRole('link', { name: 'Datos de mi cuenta', exact: true }).click()
  await expect(account.getByLabel('Nombre y apellido', { exact: true })).not.toHaveValue('Sin guardar')
  await account.getByRole('button', { name: 'Cerrar Mi cuenta', exact: true }).click()
  const studio = new URL(page.url()).searchParams.get('estudio')!
  await page.goto(`/studio/clientes/00000000-0000-0000-0000-000000000000?estudio=${studio}`)
  await expect(page.getByRole('alert')).toHaveText('Cliente no encontrado en este estudio.')
  await expect(page.getByRole('region', { name: 'Ficha del cliente', exact: true })).toHaveCount(0)
  await page.goto(`/studio/trabajoss?estudio=${studio}&plan=trial`)
  await expect(page.getByRole('heading', { name: 'Página no encontrada', exact: true })).toBeVisible()
  await page.getByRole('link', { name: 'Volver a trabajos', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Trabajos', exact: true })).toBeVisible()
})

test('rutas desconocidas muestran una página de error sin abrir el panel', async ({ page }) => {
  await page.goto('/esta-pagina-no-existe')
  await expect(page.getByRole('heading', { name: 'Página no encontrada', exact: true })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Ingresar', exact: true })).toHaveCount(0)
  await page.goto('/studio/trabajoss')
  await expect(page.getByRole('heading', { name: 'Página no encontrada', exact: true })).toBeVisible()
  await page.goto('/esta-pagina-no-existe')
  await page.getByRole('link', { name: 'Volver al inicio', exact: true }).click()
  await expect(page.getByRole('link', { name: 'Ingresar al estudio', exact: true })).toBeVisible()
})
