import { expect, test } from '@playwright/test'

test('planes manuales: el titular consulta su prueba y administración activa y cancela un plan', async ({ page, browser, baseURL }, testInfo) => {
  test.skip(process.env.TEST_API !== '1' || process.env.AUTH_REQUIRE_VERIFIED_EMAIL === 'true', 'Requiere API temporal')
  test.setTimeout(90_000)
  page.setDefaultTimeout(10_000)
  const email = `planes-${testInfo.project.name}-${Date.now()}@example.com`
  await page.goto('/studio')
  await page.getByRole('button', { name: 'Crear una cuenta', exact: true }).click()
  await page.getByLabel('Email', { exact: true }).fill(email)
  await page.getByLabel('Contraseña', { exact: true }).fill('Test-password-123!')
  await page.getByRole('button', { name: 'Registrarme', exact: true }).click()
  await page.getByRole('link', { name: 'Mi cuenta', exact: true }).click()
  const account = page.getByRole('dialog', { name: 'Mi cuenta', exact: true })
  await account.getByRole('link', { name: 'Mi plan', exact: true }).click()
  await expect(account.getByText('Prueba', { exact: true })).toBeVisible()
  await expect(account.getByText('Durante esta etapa de pruebas los límites comerciales no bloquean el uso.', { exact: true })).toBeVisible()
  await expect(account.getByRole('button', { name: 'Asignar o renovar plan', exact: true })).toHaveCount(0)
  const adminContext = await browser.newContext({ baseURL, viewport: page.viewportSize() || undefined })
  try {
    const admin = await adminContext.newPage()
    await admin.goto('/studio')
    await admin.getByLabel('Email', { exact: true }).fill(process.env.TEST_ADMIN_EMAIL!)
    await admin.getByLabel('Contraseña', { exact: true }).fill('Test-password-123!')
    await admin.getByRole('button', { name: 'Ingresar', exact: true }).click()
    await expect(admin.getByRole('link', { name: 'Mi cuenta', exact: true })).toBeVisible()
    await admin.goto(`/studio/usuarios?buscar=${encodeURIComponent(email)}`)
    await admin.getByRole('button', { name: `Gestionar plan de ${email}`, exact: true }).click()
    const panel = admin.getByRole('dialog', { name: 'Gestionar plan', exact: true })
    await expect(panel.getByText('Prueba', { exact: true }).first()).toBeVisible()
    await panel.getByRole('combobox', { name: 'Plan', exact: true }).selectOption('professional')
    await expect(panel.getByRole('combobox', { name: 'Período a habilitar', exact: true })).toHaveValue('monthly')
    await panel.getByLabel('Meses a habilitar', { exact: true }).fill('1')
    await panel.getByLabel('Nota administrativa', { exact: true }).fill('Activación de prueba acordada')
    admin.once('dialog', dialog => dialog.accept())
    await panel.getByRole('button', { name: 'Asignar o renovar plan', exact: true }).click()
    await expect(panel.getByRole('status')).toContainText('Plan actualizado. No se realizó ningún cobro.')
    await expect(panel.getByText('Profesional · Mensual', { exact: true }).first()).toBeVisible()
    await panel.getByText('Historial de cambios', { exact: true }).click()
    await expect(panel.getByText('Activación de prueba acordada', { exact: true })).toBeVisible()
    expect(await admin.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await admin.screenshot({ path: testInfo.outputPath('gestion-plan.png') })
    await panel.getByLabel('Nota administrativa', { exact: true }).fill('No renovar al finalizar')
    admin.once('dialog', dialog => dialog.accept())
    await panel.getByRole('button', { name: 'Cancelar al finalizar el período', exact: true }).click()
    await expect(panel.getByRole('status')).toContainText('Cancelación programada.')
    await panel.getByRole('button', { name: 'Cerrar gestión del plan', exact: true }).click()
    const row = admin.getByRole('table', { name: 'Usuarios registrados', exact: true }).getByRole('row').filter({ hasText: email })
    await expect(row).toContainText('Profesional')
    await expect(row).toContainText('Cancelación programada')
    await page.reload()
    await expect(account.getByRole('link', { name: 'Mi plan', exact: true })).toHaveAttribute('aria-current', 'page')
    await expect(account.getByText('Profesional · Mensual', { exact: true }).first()).toBeVisible()
    await expect(account.getByText('Cancelación programada: acceso hasta terminar el período', { exact: true })).toBeVisible()
    await expect(account.getByRole('button', { name: 'Cancelar al finalizar el período', exact: true })).toHaveCount(0)
    await page.screenshot({ path: testInfo.outputPath('mi-plan.png') })
  } finally { await adminContext.close() }
})
