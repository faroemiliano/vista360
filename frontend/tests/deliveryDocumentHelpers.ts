import { expect } from '@playwright/test'
import { readFile } from 'node:fs/promises'
import type { Page, TestInfo } from '@playwright/test'

export async function checkDeliveryDocument(page: Page, testInfo: TestInfo, link: string, maps: string) {
  const section = page.getByRole('region', { name: 'PDF de entrega', exact: true })
  const form = section.getByRole('form', { name: 'Datos del PDF de entrega', exact: true })
  const conditions = 'Alojamiento incluido: 6 meses desde la entrega.\nUna ronda de ajustes de textos y conexiones durante los primeros 7 días.\nNuevas fotografías y renovaciones se cotizan por separado.'
  await expect(section.getByRole('button', { name: 'Generar y guardar PDF', exact: true })).toBeDisabled()
  await form.getByLabel('Estudio o fotógrafo responsable', { exact: true }).fill('Emiliano Fotografía 360°')
  await form.getByLabel('Contacto para el cliente', { exact: true }).fill('estudio@example.com · +54 9 11 2345 6789')
  await form.getByLabel('Condiciones de entrega', { exact: true }).fill(conditions)
  page.once('dialog', dialog => dialog.dismiss())
  await page.getByRole('group', { name: 'Pasos del trabajo', exact: true }).getByRole('button', { name: '2 Visita', exact: true }).click()
  await expect(form.getByLabel('Condiciones de entrega', { exact: true })).toHaveValue(conditions)
  await form.getByRole('button', { name: 'Guardar datos del PDF', exact: true }).click()
  await expect(section.getByRole('status')).toHaveText('Datos guardados. Generá el PDF para incluirlos en el archivo.')
  await page.reload()
  await expect(form.getByLabel('Condiciones de entrega', { exact: true })).toHaveValue(conditions)
  await section.getByRole('button', { name: 'Generar y guardar PDF', exact: true }).click()
  const card = section.getByRole('article', { name: 'Archivo PDF guardado', exact: true })
  const view = card.getByRole('link', { name: 'Ver PDF', exact: true })
  const download = card.getByRole('link', { name: 'Descargar PDF', exact: true })
  await expect(card).toBeVisible()
  await expect(form).toBeHidden()
  await expect(view).toHaveAttribute('target', '_blank')
  const originalUrl = (await view.getAttribute('href'))!
  const inline = await page.request.get(originalUrl)
  expect(inline.status()).toBe(200)
  expect(inline.headers()['content-type']).toBe('application/pdf')
  expect(inline.headers()['content-disposition']).toMatch(/^inline;/)
  const bytes = await inline.body()
  expect(bytes.subarray(0, 5).toString()).toBe('%PDF-')
  expect(bytes.toString('latin1')).toContain(link)
  expect(bytes.toString('latin1')).toContain(maps)
  const downloading = page.waitForEvent('download')
  await download.click()
  const downloaded = await downloading
  expect(downloaded.suggestedFilename()).toMatch(/^Entrega_Estudio-(?:mobile-)?chromium-\d+_Trabajo-Hotel-Spa-(?:mobile-)?chromium-\d+_\d{4}-\d{2}-\d{2}_[a-f\d]{8}\.pdf$/)
  const local = await downloaded.path()
  expect(await readFile(local!)).toEqual(bytes)
  await downloaded.saveAs(testInfo.outputPath(downloaded.suggestedFilename()))
  await page.reload()
  await expect(view).toHaveAttribute('href', originalUrl)
  expect(await (await page.request.get(originalUrl)).body()).toEqual(bytes)
  await section.getByText('Editar documento', { exact: true }).click()
  await form.getByLabel('Condiciones de entrega', { exact: true }).fill('Condiciones nuevas, el archivo anterior se conserva hasta regenerar.')
  await form.getByRole('button', { name: 'Guardar datos del PDF', exact: true }).click()
  await expect(section.getByRole('status')).toHaveText('Datos guardados. Generá el PDF para incluirlos en el archivo.')
  expect(await (await page.request.get(originalUrl)).body()).toEqual(bytes)
  page.once('dialog', dialog => dialog.dismiss())
  await section.getByRole('button', { name: 'Generar nuevo PDF', exact: true }).click()
  await expect(view).toHaveAttribute('href', originalUrl)
  await page.getByRole('combobox', { name: 'Idioma', exact: true }).selectOption('pt-BR')
  page.once('dialog', dialog => dialog.accept())
  await section.getByRole('button', { name: 'Gerar novo PDF', exact: true }).click()
  await expect(section.getByRole('status')).toHaveText('PDF gerado e salvo neste trabalho. Você já pode visualizá-lo ou baixá-lo.')
  const portugueseCard = page.getByRole('article', { name: 'Arquivo PDF salvo', exact: true })
  const nextUrl = (await portugueseCard.getByRole('link', { name: 'Ver PDF', exact: true }).getAttribute('href'))!
  expect(nextUrl).not.toBe(originalUrl)
  await expect(page.getByRole('form', { name: 'Dados do PDF de entrega', exact: true })).toBeHidden()
  expect(await (await page.request.get(nextUrl)).body()).not.toEqual(bytes)
  expect((await page.request.get(originalUrl)).status()).toBe(404)
  await expect(portugueseCard.getByRole('link', { name: 'Baixar PDF', exact: true })).toBeVisible()
  await page.getByRole('combobox', { name: 'Idioma', exact: true }).selectOption('es')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: testInfo.outputPath('pdf-archivo-guardado.png'), fullPage: true })
}
