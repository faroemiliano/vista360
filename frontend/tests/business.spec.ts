test('landing recibe una solicitud y sólo administración puede gestionarla', async ({ page }, testInfo) => {
  test.skip(process.env.TEST_API !== '1', 'Requiere API y PostgreSQL de prueba')
  test.setTimeout(60_000)
  const name = `Solicitud ${testInfo.project.name} ${Date.now()}`
  await page.goto('/inicio')
  await expect(page.getByRole('heading', { name: 'Transformamos espacios reales en experiencias virtuales.', exact: true })).toBeVisible()
  await expect(page.getByText('Próximamente', { exact: true })).toBeVisible()
  const form = page.getByRole('form', { name: 'Solicitar digitalización', exact: true })
  await form.getByLabel('Nombre', { exact: true }).fill(name)
  await form.getByLabel('Email', { exact: true }).fill('lead-browser@example.com')
  await form.getByLabel('WhatsApp', { exact: true }).fill('+54 9 11 1234 5678')
  await form.getByRole('combobox', { name: 'Tipo de propiedad', exact: true }).selectOption('casa')
  await form.getByLabel('Localidad', { exact: true }).fill('Buenos Aires')
  await form.getByLabel('Superficie aproximada (m²)', { exact: true }).fill('85')
  await form.getByLabel('Cantidad de ambientes', { exact: true }).fill('3')
  await form.getByLabel('Mensaje adicional', { exact: true }).fill('Consulta de prueba del navegador')
  await form.getByRole('checkbox').check()
  await form.getByRole('button', { name: 'Enviar solicitud de digitalización', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Ya registramos tu consulta.', exact: true })).toBeVisible()
  await page.goto('/studio')
  await page.getByLabel('Email', { exact: true }).fill(process.env.TEST_ADMIN_EMAIL!)
  await page.getByLabel('Contraseña', { exact: true }).fill('Test-password-123!')
  await page.getByRole('button', { name: 'Ingresar', exact: true }).click()
  await navigate(page, 'Organizaciones')
  await page.getByLabel('Nombre de la organización', { exact: true }).fill(`Studio ${name}`)
  await page.getByRole('combobox', { name: 'Tipo de cuenta', exact: true }).selectOption('studio')
  await page.getByRole('button', { name: 'Crear organización', exact: true }).click()
  await expect(page.getByRole('heading', { name: `Studio ${name}`, exact: true })).toBeVisible()
  await navigate(page, 'Trabajos')
  await page.getByRole('combobox', { name: 'Organización de trabajo', exact: true }).selectOption({ label: `Studio ${name}` })
  await navigate(page, 'Solicitudes Studio')
  const job = page.getByRole('article').filter({ has: page.getByRole('heading', { name, exact: true }) })
  await expect(job).toContainText('SOLICITADO')
  await expect(job.getByRole('combobox', { name: 'Nuevo estado', exact: true }).locator('option:not([disabled])')).toHaveCount(8)
  await job.getByRole('combobox', { name: 'Nuevo estado', exact: true }).selectOption('EN_REVISION')
  await job.getByRole('button', { name: 'Actualizar estado', exact: true }).click()
  await expect(job.locator('.badge')).toHaveText('EN REVISION')
  await job.getByRole('combobox', { name: 'Nuevo estado', exact: true }).selectOption('PRESUPUESTADO')
  await job.getByLabel('Nota interna', { exact: true }).fill('Revisado por el equipo')
  await job.getByRole('button', { name: 'Actualizar estado', exact: true }).click()
  await expect(job.locator('.badge')).toHaveText('PRESUPUESTADO')
  await expect(job.getByRole('combobox', { name: 'Nuevo estado', exact: true })).toHaveValue('')
  await expect(job.getByLabel('Nota interna', { exact: true })).toHaveValue('')
  await job.getByRole('button', { name: 'Ver historial', exact: true }).click()
  await expect(job).toContainText('Revisado por el equipo')
  await page.screenshot({ path: testInfo.outputPath('studio-requests.png'), fullPage: true })
  await job.getByRole('button', { name: `Preparar trabajo para ${name}`, exact: true }).click()
  await page.getByLabel('Nombre del trabajo', { exact: true }).fill(`Visita ${name}`)
  await page.getByRole('button', { name: 'Guardar y abrir trabajo', exact: true }).click()
  await expect(page.getByRole('heading', { name: `Visita ${name}`, exact: true })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Coordinación del trabajo', exact: true })).toBeVisible()
})

test('organización registra cartera, reutiliza el editor y comparte con un colaborador de lectura', async ({ page, browser }, testInfo) => {
  test.skip(process.env.TEST_API !== '1', 'Requiere API y PostgreSQL de prueba')
  test.setTimeout(90_000)
  const stamp = `${testInfo.project.name}-${Date.now()}`
  const team = `Equipo ${stamp}`
  await page.goto('/studio')
  await page.getByRole('button', { name: 'Crear una cuenta', exact: true }).click()
  await page.getByLabel('Email', { exact: true }).fill(`owner-${stamp}@example.com`)
  await page.getByLabel('Contraseña', { exact: true }).fill('Test-password-123!')
  await page.getByRole('button', { name: 'Registrarme', exact: true }).click()
  await navigate(page, 'Organizaciones')
  await page.getByLabel('Nombre de la organización', { exact: true }).fill(team)
  await page.getByRole('button', { name: 'Crear organización', exact: true }).click()
  await navigate(page, 'Gestionar propiedades')
  await page.getByLabel('Nombre de la propiedad', { exact: true }).fill('Casa de prueba')
  await page.getByLabel('Localidad', { exact: true }).fill('Buenos Aires')
  await page.getByRole('button', { name: 'Guardar propiedad', exact: true }).click()
  await page.getByRole('button', { name: 'Editar propiedad Casa de prueba', exact: true }).click()
  await page.getByLabel('Dirección interna', { exact: true }).fill('Dirección de prueba 123')
  await page.getByRole('button', { name: 'Guardar propiedad', exact: true }).click()
  await expect(page.getByText('Dirección de prueba 123', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Crear recorrido para Casa de prueba', exact: true }).click()
  await page.getByRole('button', { name: 'Abrir Casa de prueba', exact: true }).click()
  await page.getByLabel('Nombre del ambiente', { exact: true }).fill('Living')
  await page.getByRole('button', { name: 'Agregar ambiente', exact: true }).click()
  await page.getByLabel('Panorámica JPEG para Living', { exact: true }).setInputFiles(process.env.TEST_PANORAMA_FILE!)
  await page.getByRole('button', { name: 'Subir panorámica', exact: true }).click()
  await expect(page.getByText('Panorámica validada.', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Previsualizar recorrido', exact: true }).click()
  await expect(page.locator('.viewer-frame')).toHaveAttribute('data-status', 'ready')
  await page.getByRole('button', { name: 'Cerrar previsualización', exact: true }).click()
  const reader = await browser.newContext({ viewport: testInfo.project.use.viewport })
  try {
    const visitor = await reader.newPage()
    await visitor.goto('http://127.0.0.1:5176/studio')
    await visitor.getByRole('button', { name: 'Crear una cuenta', exact: true }).click()
    await visitor.getByLabel('Email', { exact: true }).fill(`reader-${stamp}@example.com`)
    await visitor.getByLabel('Contraseña', { exact: true }).fill('Test-password-123!')
    await visitor.getByRole('button', { name: 'Registrarme', exact: true }).click()
    await expect(visitor.getByRole('heading', { name: 'Trabajos', exact: true })).toBeVisible()
    await navigate(page, 'Gestionar equipo')
    await page.getByLabel('Email de la cuenta', { exact: true }).fill(`reader-${stamp}@example.com`)
    await page.getByRole('combobox', { name: 'Rol', exact: true }).selectOption('viewer')
    await page.getByRole('button', { name: 'Guardar acceso', exact: true }).click()
    await expect(page.getByText(`reader-${stamp}@example.com`, { exact: true })).toBeVisible()
    await navigate(visitor, 'Organizaciones')
    await visitor.getByRole('button', { name: `Abrir organización ${team}`, exact: true }).click()
    await navigate(visitor, 'Gestionar recorridos')
    await visitor.getByRole('button', { name: 'Abrir Casa de prueba', exact: true }).click()
    await expect(visitor.getByRole('heading', { name: 'Previsualización privada', exact: true })).toBeVisible()
    await expect(visitor.locator('.viewer-frame')).toHaveAttribute('data-status', 'ready')
    await expect(visitor.getByRole('button', { name: 'Guardar vista actual como inicial', exact: true })).toHaveCount(0)
    await navigate(visitor, 'Gestionar equipo')
    await expect(visitor.getByRole('heading', { name: 'Equipo', exact: true })).toBeVisible()
    await expect(visitor.getByText('Sólo propietarios y administradores pueden gestionar el equipo de esta organización.', { exact: false })).toBeVisible()
    await expect(visitor.getByLabel('Email de la cuenta', { exact: true })).toHaveCount(0)
  } finally { await reader.close() }
})
