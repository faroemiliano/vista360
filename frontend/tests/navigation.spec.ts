import { expect, test } from '@playwright/test'
import { navigate } from './navigationHelpers'

test('Clientes usa una cartera unificada sin alta duplicada ni Configuración', async ({ page }, testInfo) => {
  test.skip(process.env.TEST_API !== '1', 'Requiere API y PostgreSQL temporal')
  test.setTimeout(60_000)
  page.setDefaultTimeout(10_000)
  const stamp = `${testInfo.project.name}-${Date.now()}`
  const first = `Remax ${stamp}`
  const second = `Empresa B ${stamp}`
  const person = `Fernando ${stamp}`
  await page.goto('/studio')
  await page.getByRole('button', { name: 'Crear una cuenta', exact: true }).click()
  await page.getByLabel('Email', { exact: true }).fill(`navigation-${stamp}@example.com`)
  await page.getByLabel('Contraseña', { exact: true }).fill('Test-password-123!')
  await page.getByRole('button', { name: 'Registrarme', exact: true }).click()
  await navigate(page, 'Gestionar clientes')
  await expect(page.getByRole('heading', { name: 'Clientes', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Configuración', exact: true, includeHidden: true })).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Guardar cliente', exact: true })).toHaveCount(0)
  await expect(page.getByLabel('Nombre del cliente', { exact: true })).toHaveCount(0)
  for (const name of [first, second]) {
    await navigate(page, 'Organizaciones')
    await page.getByLabel('Nombre de la organización', { exact: true }).fill(name)
    await page.getByRole('button', { name: 'Crear organización', exact: true }).click()
    await expect(page.getByRole('heading', { name, exact: true })).toBeVisible()
  }
  await navigate(page, 'Particulares')
  await page.getByLabel('Nombre del particular', { exact: true }).fill(person)
  await page.getByRole('button', { name: 'Crear particular', exact: true }).click()
  await expect(page.getByRole('heading', { name: person, exact: true })).toBeVisible()
  await navigate(page, 'Gestionar clientes')
  const table = page.getByRole('table', { name: 'Clientes', exact: true })
  const rows = table.locator('tbody tr')
  await expect(table).toBeVisible()
  await expect(rows).toHaveCount(3)
  await expect(table.getByRole('rowheader', { name: first, exact: true })).toHaveCount(1)
  await page.getByRole('combobox', { name: 'Tipo de cliente', exact: true }).selectOption('organization')
  await expect(rows).toHaveCount(2)
  await expect(table.getByRole('rowheader', { name: person, exact: true })).toHaveCount(0)
  await page.getByRole('combobox', { name: 'Tipo de cliente', exact: true }).selectOption('individual')
  await expect(rows).toHaveCount(1)
  await expect(table.getByRole('rowheader', { name: person, exact: true })).toBeVisible()
  await page.getByRole('combobox', { name: 'Tipo de cliente', exact: true }).selectOption('all')
  await page.getByLabel('Buscar cliente', { exact: true }).fill('Remax')
  await expect(rows).toHaveCount(1)
  await page.getByLabel('Buscar cliente', { exact: true }).fill('No existe este cliente')
  await expect(page.getByText('No hay clientes que coincidan con tu búsqueda.', { exact: true })).toBeVisible()
  await page.getByLabel('Buscar cliente', { exact: true }).fill('')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.screenshot({ path: testInfo.outputPath('clientes-unificados.png'), fullPage: true })
  await page.getByRole('button', { name: `Ver recorridos de ${first}`, exact: true }).click()
  await expect(page.getByRole('heading', { name: `Recorridos de ${first}`, exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Organizaciones', exact: true, includeHidden: true })).toHaveAttribute('aria-current', 'page')
  await navigate(page, 'Gestionar clientes')
  await page.getByRole('button', { name: `Ver trabajos de ${second}`, exact: true }).click()
  await expect(page.getByRole('combobox', { name: 'Cliente del trabajo', exact: true }).locator('option:checked')).toHaveText(second)
  await navigate(page, 'Gestionar clientes')
  page.once('dialog', (dialog) => dialog.dismiss())
  await page.getByRole('button', { name: `Eliminar cliente ${person}`, exact: true }).click()
  await expect(table.getByRole('rowheader', { name: person, exact: true })).toBeVisible()
  page.once('dialog', (dialog) => dialog.accept())
  await page.getByRole('button', { name: `Eliminar cliente ${person}`, exact: true }).click()
  await expect(table.getByRole('rowheader', { name: person, exact: true })).toHaveCount(0)
  await navigate(page, 'Particulares')
  await expect(page.getByRole('button', { name: `Abrir particular ${person}`, exact: true })).toHaveCount(0)
  await page.reload()
  await navigate(page, 'Gestionar clientes')
  await expect(rows).toHaveCount(2)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
})
