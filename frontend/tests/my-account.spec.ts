import { expect, test } from '@playwright/test'
import { tokenFor } from './accountFixtures'

test('Mi cuenta guarda nombre, empresa, teléfono, foto y cambio confirmado de email', async ({ page, browser, baseURL }, testInfo) => {
  test.skip(process.env.TEST_API !== '1' || process.env.AUTH_REQUIRE_VERIFIED_EMAIL === 'true', 'Requiere API temporal en modo de prueba')
  test.setTimeout(90_000)
  page.setDefaultTimeout(10_000)
  const stamp = `${testInfo.project.name}-${Date.now()}`
  const email = `cuenta-${stamp}@example.com`, newEmail = `nueva-${stamp}@example.com`
  await page.goto('/studio')
  await page.getByRole('button', { name: 'Crear una cuenta', exact: true }).click()
  await page.getByLabel('Email', { exact: true }).fill(email)
  await page.getByLabel('Contraseña', { exact: true }).fill('Test-password-123!')
  await page.getByRole('button', { name: 'Registrarme', exact: true }).click()
  await page.getByRole('button', { name: 'Mi cuenta', exact: true }).click()
  const account = page.getByRole('dialog', { name: 'Mi cuenta', exact: true })
  const form = account.getByRole('form', { name: 'Datos de mi cuenta', exact: true })
  await form.getByLabel('Nombre y apellido', { exact: true }).fill('Emiliano Prueba')
  await form.getByRole('combobox', { name: 'Tipo de cuenta', exact: true }).selectOption('company')
  await form.getByLabel('Teléfono', { exact: true }).fill('+54 9 11 2345-6789')
  await form.getByLabel('Nombre de la empresa', { exact: true }).fill('Estudio de prueba')
  await form.getByRole('button', { name: 'Guardar datos de mi cuenta', exact: true }).click()
  await expect(account.getByRole('status')).toContainText('Datos de cuenta guardados')
  await account.getByLabel('Foto de perfil', { exact: true }).setInputFiles(process.env.TEST_PANORAMA_FILE!)
  await expect(account.getByRole('status')).toContainText('Foto de perfil actualizada')
  await expect(account.getByRole('img', { name: 'Foto de perfil', exact: true })).toBeVisible()
  await expect.poll(() => account.getByRole('img', { name: 'Foto de perfil', exact: true }).evaluate(element => (element as HTMLImageElement).naturalWidth)).toBe(256)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: testInfo.outputPath('mi-cuenta.png') })
  await account.getByRole('button', { name: 'Cerrar Mi cuenta', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Mi cuenta', exact: true })).toContainText('Emiliano Prueba')
  await page.reload()
  await page.getByRole('button', { name: 'Mi cuenta', exact: true }).click()
  await expect(form.getByLabel('Nombre y apellido', { exact: true })).toHaveValue('Emiliano Prueba')
  await expect(form.getByRole('combobox', { name: 'Tipo de cuenta', exact: true })).toHaveValue('company')
  await expect(account.getByRole('img', { name: 'Foto de perfil', exact: true })).toBeVisible()
  await account.getByRole('button', { name: 'Quitar foto', exact: true }).click()
  await expect(account.getByRole('status')).toContainText('Foto eliminada')
  await expect(account.getByRole('img', { name: 'Foto de perfil', exact: true })).toHaveCount(0)
  await account.getByRole('button', { name: 'Email y contraseña', exact: true }).click()
  await account.getByText('Cambiar email de acceso', { exact: true }).click()
  const emailForm = account.getByRole('form', { name: 'Cambiar email', exact: true })
  await emailForm.getByLabel('Nuevo email', { exact: true }).fill(newEmail)
  await emailForm.getByLabel('Contraseña actual para cambiar email', { exact: true }).fill('Test-password-123!')
  await emailForm.getByRole('button', { name: 'Solicitar cambio de email', exact: true }).click()
  await expect(account.getByRole('status')).toContainText('Seguí ingresando con tu email actual')
  const token = tokenFor(email, 'change_email')
  const visitorContext = await browser.newContext({ baseURL })
  try {
    const visitor = await visitorContext.newPage()
    await visitor.goto(`/cuenta/email#token=${token}`)
    await visitor.getByRole('button', { name: 'Confirmar nuevo email', exact: true }).click()
    await expect(visitor.getByRole('status')).toContainText('Email actualizado y verificado')
    await page.reload()
    await expect(page.getByRole('button', { name: 'Ingresar', exact: true })).toBeVisible()
    await page.getByLabel('Email', { exact: true }).fill(newEmail)
    await page.getByLabel('Contraseña', { exact: true }).fill('Test-password-123!')
    await page.getByRole('button', { name: 'Ingresar', exact: true }).click()
    await expect(page.getByRole('button', { name: 'Mi cuenta', exact: true })).toContainText('Emiliano Prueba')
    await page.getByRole('button', { name: 'Mi cuenta', exact: true }).click()
    await account.getByRole('button', { name: 'Cerrar sesión', exact: true }).click()
    await expect(page.getByRole('button', { name: 'Ingresar', exact: true })).toBeVisible()
  } finally { await visitorContext.close() }
})
